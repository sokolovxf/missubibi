"""## 13. Tabular Transformer Architecture (Cardinality-Aware Embeddings + Residual Head)

Follows a **TabTransformer**-style design (Huang et al. 2020) for the categorical
tokens, unchanged from Rev 3:

- **Cardinality-aware embedding sizing.** Each categorical column gets its own raw
  embedding width, scaled to its vocabulary size via `embed_dim_for_vocab` (small for
  `calendar_quarter`'s 4 categories, larger for `item_internal_id`'s much bigger
  vocabulary), then a per-column `Dense` projects every token to the shared `EMBED_DIM`
  so the attention stack still operates on a uniform token width.

**Rev 4 addition — a proper residual MLP head.** The fused categorical+numeric
representation now passes through explicit `x + F(x)` residual blocks (pre-activation,
`LayerNormalization`-gated) instead of a plain stacked-`Dense` head. This restores the
"residual blocks" element from the original architecture brief with real skip
connections rather than the Transformer's internal residuals alone, giving the head
more effective depth without the vanishing-gradient risk a plain deep stack would carry.

"""

EMBED_DIM = 32          # shared width tokens are projected to before attention
NUM_HEADS = 4
FF_DIM = 64
NUM_TRANSFORMER_BLOCKS = 2
DROPOUT_RATE = 0.2
CAT_TOKEN_DROPOUT_RATE = 0.15
EMBED_DROPOUT_RATE = 0.10     # Rev 5: per-feature embedding dropout (see build_tab_transformer)
ATTENTION_KEY_DIM = 16        # Rev 5: decoupled from EMBED_DIM // NUM_HEADS (see TransformerBlock)
EMBEDDING_L2 = 1e-5
MLP_L2 = 1e-5
LABEL_SMOOTHING = 0.03
RESIDUAL_HEAD_WIDTH = 128
NUM_RESIDUAL_BLOCKS = 2

def embed_dim_for_vocab(vocab_size, min_dim=8, max_dim=48):
    '''Scale raw embedding width to vocabulary size (small vocab -> small embedding,
    large vocab -> larger embedding), capped to a sane range.'''
    heuristic = int(round(1.6 * (vocab_size ** 0.56)))
    return int(np.clip(heuristic, min_dim, max_dim))


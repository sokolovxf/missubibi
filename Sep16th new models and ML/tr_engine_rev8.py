"""## 9. Binary Target: Sold vs Did Not Sell

### What this label actually is (and why Rev 8 stopped calling it a percentile)

Rev 4–7 defined the target as "quantity at or above the **66th percentile** of training
quantity", and named the classes *High Demand* vs *Normal/Low Demand*. On the
calendar-gap panel that percentile evaluated to exactly **`1.0`**, so the rule had
already collapsed to `quantity >= 1` — the label was never a high-vs-normal split, it
was **sold vs did not sell**, wearing the wrong name.

On Rev 8's full-calendar panel the percentile does not merely collapse, it *breaks*:
explicit zero-sales rows are now the majority of the panel, so the 66th percentile of
quantity is **`0.0`** and `quantity >= 0` would label every single row positive — a
degenerate, 100%-accuracy-by-construction target.

So Rev 8 states the target directly as `quantity >= 1` and names the classes for what
they are. **This is not a change of task** — it is the same label Rev 7 actually trained
on, written honestly and made robust to the panel change. `qty_threshold` is kept (at
1.0) because Section 10's persistence baseline is defined against it.

Read every downstream number as answering *"will this item sell at all next month?"*,
and always against the Section 10 baselines, which are computed on the identical
population.

"""

# Rev 8: the target is stated directly instead of being derived from a quantile.
# See the markdown above -- the Rev 4-7 66th-percentile rule already evaluated to
# exactly this on the old panel, and on the full-calendar panel it would degenerate to
# "label everything positive". The percentile is still computed, purely so the notebook
# prints the evidence for that claim rather than asking you to take it on trust.
_legacy_q = train_df["quantity"].quantile(0.66)
print(f"Legacy Rev 4-7 rule (66th pct of train quantity) would give threshold: {_legacy_q:.2f}")

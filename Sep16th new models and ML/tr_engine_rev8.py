"""## 12. Scale Numerics (fit on TRAIN only) & Prepare Model Inputs

**Rev 4 optimization:** categorical string arrays are now built directly with
`.to_numpy().astype(str)` instead of the Rev 3 round-trip through `.tolist()` and
`np.array(..., dtype="U")`, which is both simpler and meaningfully faster on larger
datasets. Inputs are still kept as plain dict-of-arrays here (needed for `model.predict`
on validation/test); Section 14 wraps the *training* dict in a `tf.data.Dataset` for
the actual `model.fit()` call.

"""

scaler = StandardScaler()
X_train_num = scaler.fit_transform(train_df[NUMERIC_FEATURES]).astype("float32")

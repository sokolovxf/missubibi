def build_input_dict(df, num_array):
    """Builds the dict model.fit()/model.predict() expects.

    IMPORTANT: pandas/NumPy will happily hand back a fixed-width '<U..' (str64-style)
    array from a naive `df[c].values` or `np.array(df[c].tolist())` call. tf.string
    Input layers reject that dtype outright (`ValueError: Invalid dtype: str64`) even
    though the *values* are fine -- TensorFlow only accepts Python strings packed in a
    NumPy `object` array. `.astype(str).to_numpy(dtype=object)` is what forces that.
    """
    d = {"numeric_input": num_array}
    for c in CATEGORICAL_FEATURES:
        arr = df[c].astype(str).to_numpy(dtype=object).reshape(-1, 1)
        d[c] = arr
    return d

def assert_tf_string_compatible(inputs_dict, categorical_cols):
    """Defensive hygiene check (Rev 5): fail loudly, at build time, if any categorical
    array is anything other than a NumPy object array of Python str -- instead of
    letting a bad array silently reach model.predict() and surface a cryptic
    'Invalid dtype: str64' deep inside a Keras call. Cheap (kind-code check only,
    no data copy) so it's safe to run on every train/val/test dict."""
    for c in categorical_cols:
        arr = inputs_dict[c]
        if arr.dtype != object:
            raise TypeError(
                f"Categorical input '{c}' has dtype {arr.dtype!r} (kind={arr.dtype.kind!r}); "
                f"tf.string Input layers require dtype=object arrays of Python str. "
                f"This usually means a '<U..' / str64 array slipped in -- rebuild it with "
                f".astype(str).to_numpy(dtype=object).reshape(-1, 1)."
            )
        sample = arr.reshape(-1)[0] if arr.size else ""
        if not isinstance(sample, str):
            raise TypeError(f"Categorical input '{c}' is dtype=object but its elements are "
                             f"{type(sample)}, not str -- check the source column.")

def to_model_inputs(inputs_dict):
    """Rev 6: convert every array to an explicit tf.Tensor right before it touches the
    model/Dataset, instead of relying on Keras's internal numpy->tensor dtype inference.

    Why this exists even though build_input_dict already produces dtype=object arrays:
    on Keras 3 (which `tensorflow.keras` now aliases to on TF>=2.16), model.fit/predict
    and tf.data.Dataset.from_tensor_slices each do their own internal dtype
    canonicalization via `keras.backend.standardize_dtype`. On some TF/Keras 3 version
    combinations that internal path re-derives a NumPy dtype from the array rather than
    trusting a plain `dtype=object` array of Python str, and if that re-derivation ever
    produces a fixed-width unicode array (e.g. NumPy's `<U2`, whose `.name` is
    'str64' -- hence the exact error text) you get `ValueError: Invalid dtype: str64`
    even though build_input_dict's array was correct. Explicitly building the
    tf.string / tf.float32 tensors ourselves, with tf.convert_to_tensor, sidesteps that
    internal inference entirely -- there's nothing left for Keras to reinterpret.
    """
    out = {}
    for k, v in inputs_dict.items():
        if k == "numeric_input":
            out[k] = tf.convert_to_tensor(v, dtype=tf.float32)
        else:
            out[k] = tf.convert_to_tensor(np.asarray(v, dtype=object), dtype=tf.string)
    return out


"""## 23. Permutation Feature Importance *(Rev 4 addition)*

A direct, model-agnostic sanity check: shuffle one numeric feature at a time across
the test set (breaking its relationship to the target while leaving every other
feature and the model itself untouched), re-predict, and measure how much accuracy
drops. A larger drop means the model relies on that feature more. This is computed
**after** all evaluation above and uses only the already-held-out test set purely as a
diagnostic — it does not feed back into training, thresholding, or any reported metric.

"""

def permutation_importance_numeric(model, inputs_dict, numeric_cols, y_true, baseline_acc,
                                    threshold, n_repeats=3, seed=SEED):
    rng = np.random.default_rng(seed)
    importances = {}
    base_numeric = inputs_dict["numeric_input"].copy()

    for j, col in enumerate(numeric_cols):
        drops = []
        for _ in range(n_repeats):
            permuted = base_numeric.copy()
            perm_idx = rng.permutation(len(permuted))
            permuted[:, j] = permuted[perm_idx, j]
            permuted_inputs = dict(inputs_dict)
            permuted_inputs["numeric_input"] = permuted
            proba = model.predict(to_model_inputs(permuted_inputs), batch_size=256, verbose=0).ravel()
            pred = (proba >= threshold).astype(int)
            acc = accuracy_score(y_true, pred)
            drops.append(baseline_acc - acc)
        importances[col] = float(np.mean(drops))
    return importances

perm_importances = permutation_importance_numeric(
    model, test_inputs, NUMERIC_FEATURES, y_test, test_accuracy, best_threshold, n_repeats=3
)

perm_df = pd.DataFrame({
    "Feature": list(perm_importances.keys()),
    "Accuracy Drop": list(perm_importances.values()),
}).sort_values("Accuracy Drop", ascending=True)


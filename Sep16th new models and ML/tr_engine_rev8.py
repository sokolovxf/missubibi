"""## 6. Aggregate to Item–Month Level (full-calendar panel)

The modeling grain is **item x calendar month**. We aggregate every month that actually
had sales, then reindex each item onto a complete monthly calendar so a month with no
sales becomes an explicit `quantity = 0` row instead of a missing row that `.shift()`
would silently skip over.

### ⚠️ Rev 8 leakage fix — how far each item's panel extends

Rev 3–7 reindexed each item from its first sale month to **its own last sale month**.
That quietly put future information into the *row set itself*:

* a row existed at month `t` only if that item sold again at some month `>= t`, so the
  mere presence of a row told the model the item was not yet dead; and
* every item's final row was, by construction, guaranteed to be a sale.

Neither fact is knowable at prediction time. Rev 8 reindexes every item from its first
sale month to the **global end of the observed calendar** instead. Nothing outside the
observed data range is fabricated — items simply keep receiving explicit `quantity = 0`
rows after they stop selling, which is exactly what a forecasting engine must predict
for a live SKU that has gone quiet.

This changes the row population (and therefore every headline number downstream), so
Section 10's naive baselines are recomputed on the same population and reported next to
the model everywhere. See Section 19 and the Rev 8 note in Section 24 for the
side-by-side against the old panel.

"""

df["year_month"] = df["sales_order_date"].dt.to_period("M")

def mode_or_na(s):
    m = s.mode()
    return m.iloc[0] if not m.empty else np.nan

monthly = (
    df.groupby(["item_internal_id", "year_month"])
      .agg(
          quantity=("quantity", "sum"),
          n_orders=("so_internal_id", "nunique"),
          distinct_customers=("customer_internal_id", "nunique"),
          avg_base_price=("base_price", "mean"),
          dominant_customer_type=("customer_type", mode_or_na),
          dominant_industry=("fa_sub_industries", mode_or_na),
      )
      .reset_index()
      .sort_values(["item_internal_id", "year_month"])
      .reset_index(drop=True)
)


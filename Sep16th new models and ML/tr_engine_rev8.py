# Plain for-loop over groupby (rather than .groupby().apply()) deliberately avoids the
# include_groups / grouping-column-in-output inconsistency between pandas < 2.2 and
# pandas >= 2.2, so this behaves the same on any supported pandas version.
# Rev 8: extend every item to the LAST MONTH IN THE DATA, not to its own last sale
# month. Ending each panel at the item's own final sale leaked the future (see the
# markdown above): a row's existence implied a later sale, and each item's last row was
# always a sale. The global end is a constant, known at prediction time for every item.
GLOBAL_LAST_MONTH = monthly["year_month"].max()
print(f"Reindexing every item up to the global last observed month: {GLOBAL_LAST_MONTH}")

_reindexed_frames = []
for item_id, g in monthly.groupby("item_internal_id"):
    full_range = pd.period_range(g["year_month"].min(), GLOBAL_LAST_MONTH, freq="M")
    g2 = g.set_index("year_month").reindex(full_range)
    g2.index.name = "year_month"
    g2["item_internal_id"] = item_id
    _reindexed_frames.append(g2.reset_index())

monthly = pd.concat(_reindexed_frames, ignore_index=True)

gap_rows_added = len(monthly) - rows_before_reindex
print(f"Full-calendar panel: added {gap_rows_added:,} explicit zero-sales month rows "
      f"({rows_before_reindex:,} -> {len(monthly):,} item-month rows)")

# These are genuine zero-activity months, not missing values -> fill with 0.
# Price/segment columns for gap months stay NaN and fall through to the existing
# train-median / "MISSING" imputation later in the notebook (no leakage introduced).
monthly[["quantity", "n_orders", "distinct_customers"]] = (
    monthly[["quantity", "n_orders", "distinct_customers"]].fillna(0)
)

item_static = item[["item_internal_id", "production_status", "product_category_1",
                     "product_category_2", "list_price"]].drop_duplicates("item_internal_id")

"""## 3. Data Cleaning (Leak-Free Preparation)

We remove exact duplicates/blank rows (via `is_duplicate_row`, `is_completely_blank`,
`is_duplicate_item`, `is_duplicate_customer` if present), cancelled orders, non-positive
quantity lines, and rows missing join keys. Every drop step logs a before/after row
count so data loss is auditable rather than silent.

**Rev 4 addition — `normalize_id_col`.** ID columns occasionally arrive with
inconsistent dtypes across files (e.g. a stray null elsewhere in a file silently
upcasts an otherwise-integer ID column to `float64`, so the same item shows up as
`123` in one table and `123.0` in another). Pandas' `merge` *does* coerce numeric
dtypes during the join itself, so this rarely drops rows outright — but it's fragile
and becomes a real, silent join-key mismatch the moment an ID column contains any
non-numeric-looking value (leading zeros, mixed string/number exports, etc.). Cleaning
whole-number floats down to plain integer strings *before* casting to the string dtype
the model's `StringLookup` embeddings expect removes that fragility entirely and costs
nothing when the IDs were already clean.

"""

def normalize_id_col(s):
    '''Normalize an ID column to a clean string representation.

    Whole-number floats (e.g. 123.0, arising from an unrelated NaN elsewhere in the
    same column upcasting it to float64) are rendered as '123', matching how the same
    ID would render if the column had stayed integer/string in another table. Non
    whole-number or non-numeric values are just stringified as-is.
    '''
    def _one(v):
        if pd.isna(v):
            return v
        if isinstance(v, float) and v.is_integer():
            return str(int(v))
        return str(v)
    return s.map(_one)


def clean_sales(df, label="sales"):
    df = df.copy()
    start_n = len(df)

    for flag_col in ["is_duplicate_row", "is_completely_blank"]:
        if flag_col in df.columns:
            before = len(df)
            df = df[~df[flag_col].astype(bool)]
            print(f"[{label}] dropped {before - len(df):,} rows flagged by '{flag_col}'")

    before = len(df)
    df = df.drop_duplicates()
    print(f"[{label}] dropped {before - len(df):,} exact duplicate rows")

    required_cols = ["so_internal_id", "sales_order_date", "customer_internal_id",
                      "item_internal_id", "quantity"]
    before = len(df)
    df = df.dropna(subset=[c for c in required_cols if c in df.columns])
    print(f"[{label}] dropped {before - len(df):,} rows missing required join/key columns")

    if "sales_order_status" in df.columns:
        before = len(df)
        df = df[~df["sales_order_status"].str.contains("cancel", case=False, na=False)]
        print(f"[{label}] dropped {before - len(df):,} cancelled-order rows")

    before = len(df)
    df = df[df["quantity"] > 0]
    print(f"[{label}] dropped {before - len(df):,} zero/negative-quantity rows")

    df["sales_order_date"] = pd.to_datetime(df["sales_order_date"], errors="coerce")
    before = len(df)
    df = df.dropna(subset=["sales_order_date"])
    print(f"[{label}] dropped {before - len(df):,} rows with unparseable dates")

    # Rev 4 fix: normalize join-key dtype fragility before it ever reaches a merge.
    for id_col in ["item_internal_id", "customer_internal_id"]:
        if id_col in df.columns:
            df[id_col] = normalize_id_col(df[id_col])

    print(f"[{label}] TOTAL: {start_n:,} -> {len(df):,} rows retained ({len(df)/start_n:.1%})")
    return df.reset_index(drop=True)



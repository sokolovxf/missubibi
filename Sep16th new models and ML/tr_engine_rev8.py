test_df[NUMERIC_FEATURES]  = test_df[NUMERIC_FEATURES].fillna(train_medians).fillna(0.0)

print(f"{len(NUMERIC_FEATURES)} numeric features, {len(CATEGORICAL_FEATURES)} categorical features")
assert train_df[NUMERIC_FEATURES].isna().sum().sum() == 0, "Unexpected NaNs remain in train numerics."

class WarmupCosineDecay(tf.keras.optimizers.schedules.LearningRateSchedule):
    def __init__(self, base_lr, warmup_steps, total_steps, min_lr_ratio=0.05):
        super().__init__()
        self.base_lr = base_lr
        self.warmup_steps = max(1, warmup_steps)
        self.total_steps = max(self.warmup_steps + 1, total_steps)
        self.min_lr_ratio = min_lr_ratio

    def __call__(self, step):
        step = tf.cast(step, tf.float32)
        warmup_steps = tf.cast(self.warmup_steps, tf.float32)
        total_steps = tf.cast(self.total_steps, tf.float32)

        warmup_lr = self.base_lr * (step / warmup_steps)

        progress = (step - warmup_steps) / tf.maximum(1.0, total_steps - warmup_steps)
        progress = tf.clip_by_value(progress, 0.0, 1.0)
        cosine = 0.5 * (1.0 + tf.cos(math.pi * progress))
        decayed_lr = (self.base_lr - self.base_lr * self.min_lr_ratio) * cosine + self.base_lr * self.min_lr_ratio

        return tf.where(step < warmup_steps, warmup_lr, decayed_lr)

    def get_config(self):
        return {"base_lr": self.base_lr, "warmup_steps": self.warmup_steps,
                "total_steps": self.total_steps, "min_lr_ratio": self.min_lr_ratio}


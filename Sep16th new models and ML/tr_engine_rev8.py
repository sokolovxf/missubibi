def make_binary_focal_loss(gamma=FOCAL_GAMMA, alpha=focal_alpha, label_smoothing=LABEL_SMOOTHING):
    def focal_loss(y_true, y_pred):
        y_true = tf.cast(y_true, tf.float32)
        if label_smoothing > 0:
            y_true = y_true * (1.0 - label_smoothing) + 0.5 * label_smoothing
        eps = tf.keras.backend.epsilon()
        y_pred = tf.clip_by_value(y_pred, eps, 1.0 - eps)
        p_t = tf.where(tf.equal(tf.round(y_true), 1.0), y_pred, 1.0 - y_pred)
        alpha_factor = tf.where(tf.equal(tf.round(y_true), 1.0), alpha, 1.0 - alpha)
        loss = -alpha_factor * tf.pow(1.0 - p_t, gamma) * tf.math.log(p_t)
        return tf.reduce_mean(loss)
    return focal_loss


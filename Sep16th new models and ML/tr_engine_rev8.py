"""## 15. Compile: AdamW + Warmup/Cosine-Decay Schedule, Class-Balanced Focal Loss

Class weights (kept available as a switchable fallback) come from `y_fit` (the rows
actually used for gradient updates). The learning rate follows a short linear warmup
into a cosine decay, unchanged from Rev 3.

**Rev 4 accuracy lever — class-balanced focal loss (Lin et al., 2017) as the default
loss**, replacing plain label-smoothed BCE + `class_weight`. Focal loss down-weights
already-easy, correctly-classified examples during training via the `(1 - p_t)^gamma`
modulating factor, so gradient updates keep focusing on the harder, more ambiguous
rows instead of being dominated by the many easy majority-class negatives — this
typically sharpens minority-class (High Demand) discrimination more than a single
static `class_weight` multiplier can. `alpha` is set from the **fit-split** class
prior only (never test), and `class_weight` is intentionally left `None` when focal
loss is active so the two mechanisms are never combined (stacking both would
double-penalize the minority class and distort calibration for no accuracy benefit).
Set `USE_FOCAL_LOSS = False` below to fall back to Rev 3's plain BCE + `class_weight`
combination if you want to compare the two on your own data.

"""


# ---- 4.3  Modelling grains: monthly, fortnightly, weekly -------------------------------------
MONTHLY_INDEX = pd.DatetimeIndex(FULL_INDEX)
MONTHLY_SERIES = dict(series_dict)
WINDOW_START = MONTHLY_INDEX[0]
WINDOW_END = MONTHLY_INDEX[-1] + pd.DateOffset(months=1)      # exclusive

# period = seasonal cycle in periods of this grain; lags/rolls/cap are the grain's own
# translation of the monthly (1,2,3,12) / (3,6,12) / 6-month recency cap.
GRAIN_SETTINGS = {
    "M":  dict(period=12, step_days=None, lags=(1, 2, 3, 12), diff_lags=(1, 2),
               rolls=(3, 6, 12), cap=6, label="monthly"),
    "2W": dict(period=26, step_days=14, lags=(1, 2, 3, 13, 26), diff_lags=(1, 2),
               rolls=(2, 6, 13, 26), cap=13, label="fortnightly"),
    "W":  dict(period=52, step_days=7, lags=(1, 2, 3, 4, 52), diff_lags=(1, 2),
               rolls=(4, 13, 52), cap=26, label="weekly"),
}


def grain_index(grain, upto=None):
    """Period START timestamps at `grain`, covering the modelling window (and beyond)."""
    g = GRAIN_SETTINGS[grain]
    end = WINDOW_END if upto is None else pd.Timestamp(upto)
    if g["step_days"] is None:
        return pd.DatetimeIndex(pd.date_range(WINDOW_START, end - pd.Timedelta(days=1),
                                              freq="MS"), name="period")
    # Anchor on the first Monday on or after the window start, so `period` periods is exactly
    # one year of whole weeks.
    start = WINDOW_START + pd.Timedelta(days=int((7 - WINDOW_START.dayofweek) % 7))
    return pd.DatetimeIndex(pd.date_range(start, end - pd.Timedelta(days=1),
                                          freq=f"{g['step_days']}D"), name="period")


def grain_edges(index, grain):
    """(start, end) per period; `end` is EXCLUSIVE."""
    idx = pd.DatetimeIndex(index)
    g = GRAIN_SETTINGS[grain]
    return ((idx, idx + pd.DateOffset(months=1)) if g["step_days"] is None
            else (idx, idx + pd.Timedelta(days=int(g["step_days"]))))


def _period_pos(dates, starts, ends):
    """Right-open interval assignment of transaction dates to periods."""
    pos = np.searchsorted(starts.to_numpy(), dates, side="right") - 1
    ok = (pos >= 0) & (pos < len(starts))
    safe = np.clip(pos, 0, len(starts) - 1)
    ok &= dates < ends.to_numpy()[safe]
    return pos, ok


def grain_series(df, value_col, index, grain, category=None, cat_col=CAT_COL, exclude=None):
    """`monthly_series` over arbitrary period edges — one code path for every grain."""
    d = (df[df[cat_col] == category] if category is not None else
         df[~df[cat_col].isin(exclude)] if exclude is not None else df)
    starts, ends = grain_edges(index, grain)
    pos, ok = _period_pos(d["sales_order_date"].to_numpy(), starts, ends)
    out = np.zeros(len(starts), dtype=float)
    np.add.at(out, pos[ok], d[value_col].to_numpy(dtype=float)[ok])
    return pd.Series(out, index=pd.DatetimeIndex(starts, name="period"))


def month_allocation(index, grain, months, weight="working"):
    """A[p, m] = share of period p's activity inside month m; the identity at grain 'M'.
    WORKING-day weighting halves the conversion error against calendar days (a week straddling
    a boundary splits 0/5, not 2/5). Pure calendar arithmetic - nothing here can leak."""
    starts, ends = grain_edges(index, grain)
    ms = pd.DatetimeIndex(months)
    me = ms + pd.DateOffset(months=1)
    ps, pe = starts.to_numpy("datetime64[D]"), ends.to_numpy("datetime64[D]")
    a, b = ms.to_numpy("datetime64[D]"), me.to_numpy("datetime64[D]")
    lo = np.maximum(ps[:, None], a[None, :])
    hi = np.maximum(np.minimum(pe[:, None], b[None, :]), lo)
    if str(weight).startswith("work"):
        hol = holiday_dates(range(int(ms.min().year) - 1, int(me.max().year) + 2))
        hol = hol[hol.dayofweek < 5].values.astype("datetime64[D]")
        ov = np.busday_count(lo.ravel(), hi.ravel(), holidays=hol).reshape(lo.shape).astype(float)
    else:
        ov = (hi - lo).astype("timedelta64[D]").astype(float)
    span = ov.sum(axis=1, keepdims=True)
    if np.any(span <= 0):          # an entire period of public holidays: fall back to calendar
        cal = (hi - lo).astype("timedelta64[D]").astype(float)
        ov[(span <= 0).ravel()] = cal[(span <= 0).ravel()]
        span = ov.sum(axis=1, keepdims=True)
    return np.divide(ov, span, out=np.zeros_like(ov), where=span > 0)


# ---- 4.4  Customer-signal block (candidate features, tested in Section 8.4) -------------------
# Active customers, orders and new-vs-repeat mix per period. A customer's first-ever order
# month is a min over all rows - identical to a min over rows up to t for anyone who has
# ordered by t - and the model sees these only at a FULL SEASONAL-CYCLE LAG (self-test (k)).
EXOG_BASE_COLS = ["n_customers", "n_orders", "new_cust_share", "top_cust_share"]
_CUST_COL = "customer_internal_id" if "customer_internal_id" in model_df.columns else None
_ORDER_COL = "sales_order_number" if "sales_order_number" in model_df.columns else None
if _CUST_COL is None and _ORDER_COL is None:
    CONFIG["USE_EXOG_SIGNALS"] = CONFIG["EXOG_TRIAL"] = False
    note("REVIEW", "No customer or order id in the export, so the customer-signal block cannot "
                   "be built. That is the leading indicator most likely to be worth having.")
_FIRST_ORDER = (model_df.groupby(_CUST_COL)["sales_order_date"].min()
                if _CUST_COL else pd.Series(dtype="datetime64[ns]"))


def grain_exog(index, grain):
    """Per-period customer/order counts and new-customer share, on this grain's periods."""
    starts, ends = grain_edges(index, grain)
    n = len(starts)
    out = {c: np.full(n, np.nan) for c in EXOG_BASE_COLS}
    if not (_CUST_COL or _ORDER_COL):
        return pd.DataFrame(out, index=pd.DatetimeIndex(starts, name="period"))
    d = model_df
    pos, ok = _period_pos(d["sales_order_date"].to_numpy(), starts, ends)
    frame = pd.DataFrame({"p": pos[ok]})
    if _CUST_COL:
        frame["cust"] = d[_CUST_COL].to_numpy()[ok]
        first = d[_CUST_COL].map(_FIRST_ORDER).to_numpy()[ok]
        fpos, fok = _period_pos(first, starts, ends)
        frame["is_new"] = fok & (fpos == frame["p"].to_numpy())
        g = frame.groupby("p")
        cnt = g["cust"].nunique()
        out["n_customers"][cnt.index.to_numpy()] = cnt.to_numpy(dtype=float)
        newc = frame[frame["is_new"]].groupby("p")["cust"].nunique()
        newv = np.zeros(n)
        newv[newc.index.to_numpy()] = newc.to_numpy(dtype=float)
        with np.errstate(invalid="ignore", divide="ignore"):
            out["new_cust_share"] = np.where(out["n_customers"] > 0,
                                             newv / out["n_customers"], np.nan)
    if _ORDER_COL:
        frame["ordn"] = d[_ORDER_COL].to_numpy()[ok]
        o = frame.groupby("p")["ordn"].nunique()
        out["n_orders"][o.index.to_numpy()] = o.to_numpy(dtype=float)
    if _CUST_COL:
        # Concentration: the largest single customer's share of the period. It moves before
        # a big account leaves, which a headcount of customers does not.
        frame["rev"] = d["revenue"].to_numpy()[ok]
        by = frame.groupby(["p", "cust"])["rev"].sum()
        tot = by.groupby(level=0).sum()
        top = by.groupby(level=0).max()
        sh = (top / tot.replace(0, np.nan)).dropna()
        out["top_cust_share"][sh.index.to_numpy().astype(int)] = sh.to_numpy(dtype=float)
    df_out = pd.DataFrame(out, index=pd.DatetimeIndex(starts, name="period"))
    if EXCLUDED_FYS:       # an excluded fiscal year is untrusted as a signal too
        bad = np.isin([fy_of(t) for t in df_out.index], EXCLUDED_FYS)
        df_out.loc[bad, :] = np.nan
    return df_out



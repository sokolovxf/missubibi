# ---- 7.0b  The pinned training view ----------------------------------------------------------
def _train_cap(y):
    """Last OBSERVED position, minus the grain's recency cap."""
    obs = np.where(np.isfinite(np.asarray(y, dtype=float)))[0]
    return None if obs.size == 0 else int(max(0, int(obs[-1]) - int(CAP_PERIODS)))


def _fit_trend(y):
    """OLS line through the OBSERVED points of the training view — the blend component."""
    v = np.asarray(y, dtype=float)
    obs = np.where(np.isfinite(v))[0]
    if obs.size < 4:
        return (0.0, float(np.mean(v[obs])) if obs.size else 0.0)
    b, a = np.polyfit(obs.astype(float), v[obs], 1)
    return (float(b), float(a))


def _trend_at(ts):
    b, a = VIEW.trend
    return b * np.asarray(ts, dtype=float) + a


def _model_view(y, mode):
    """The array features and targets are built on: detrended for 'blend', y otherwise."""
    y = np.asarray(y, dtype=float)
    return y - _trend_at(np.arange(len(y))) if mode == "blend" else y.copy()


def detect_changepoint(y, min_seg=None, min_shift=None):
    """Most likely LEVEL SHIFT position in the OBSERVED part of `y`, or None. Two-mean scan;
    the minimum relative shift is what stops a smooth trend being called a break. Reads
    observed values only, and is always called on a masked training view."""
    v = np.asarray(y, dtype=float)
    obs = np.where(np.isfinite(v))[0]
    seg = (months_to_periods(CONFIG.get("REGIME_MIN_SEG_MONTHS", 6)) if min_seg is None
           else int(min_seg))
    shift_min = (float(CONFIG.get("REGIME_MIN_SHIFT_FRAC", 0.12)) if min_shift is None
                 else float(min_shift))
    if obs.size < 2 * seg + 2:
        return None
    vals = v[obs]
    best, best_k = -np.inf, None
    for k in range(seg, obs.size - seg + 1):
        a, b = vals[:k], vals[k:]
        pooled = np.sqrt(a.std(ddof=1) ** 2 / a.size + b.std(ddof=1) ** 2 / b.size)
        if not np.isfinite(pooled) or pooled <= 0:
            continue
        score = abs(float(b.mean()) - float(a.mean())) / pooled
        if score > best:
            best, best_k = score, k
    if best_k is None or not np.isfinite(best):
        return None
    ma, mb = float(vals[:best_k].mean()), float(vals[best_k:].mean())
    if abs(ma) <= 1e-9 or abs(mb - ma) / abs(ma) < shift_min:
        return None
    return int(obs[best_k])


@contextlib.contextmanager
def _set_view(y):
    """Pin the cap, changepoint and blend trend from ONE training view, and restore. Computing
    any of them inside the recursion would let a prediction move what the training rows were
    built against."""
    prev = (VIEW.cap, VIEW.regime, VIEW.trend)
    VIEW.cap = _train_cap(y)
    VIEW.regime = detect_changepoint(y) if regime_enabled() else None
    VIEW.trend = _fit_trend(y)
    try:
        yield VIEW.cap, VIEW.regime
    finally:
        VIEW.cap, VIEW.regime, VIEW.trend = prev


_set_trend_cap = _set_view      # kept under its old name; the self-tests refer to it


def _feature_row(z, t):
    """Features for predicting `z[t]`, from `z[:t]` and the calendar at `t` ONLY — the whole
    no-leakage contract, enforced by self-test (a). Unavailable history becomes NaN and is
    imputed inside the pipeline; imputing here, from the whole series, would leak."""
    z = np.asarray(z, dtype=float)
    out = []
    for L in LAGS:
        out.append(z[t - L] if t - L >= 0 else np.nan)
    for L in DIFF_LAGS:
        i = t - L
        out.append(z[i] - z[i - 1] if i - 1 >= 0 else np.nan)
    for W in ROLLS:
        w = z[max(0, t - W):t]
        w = w[np.isfinite(w)]
        out.append(float(w.mean()) if w.size else np.nan)
        out.append(float(w.std(ddof=1)) if w.size > 1 else np.nan)
    # yoy_momentum: the trailing YOY_K periods against the same YOY_K one cycle earlier. A
    # scale-free ratio that moves BEFORE a level shift reaches the lag block.
    recent = z[max(0, t - YOY_K):t]
    prior = z[max(0, t - GM - YOY_K):max(0, t - GM)]
    recent, prior = recent[np.isfinite(recent)], prior[np.isfinite(prior)]
    out.append(float(recent.mean()) / float(prior.mean()) - 1.0
               if recent.size and prior.size and abs(float(prior.mean())) > 1e-9 else np.nan)
    if CONFIG["RF_TREND_INDEX"]:
        cap = VIEW.cap
        out.append(float(t) if cap is None else float(min(t, cap)))
    if CONFIG.get("USE_REGIME_FEATURE", False):
        # Constant zero when no break cleared the threshold, and a constant column is never
        # split on, so an absent regime costs the forest nothing.
        out.append(0.0 if (VIEW.regime is None or not regime_enabled())
                   else float(t >= VIEW.regime))
    return np.concatenate([np.asarray(out, dtype=float), CAL_ARR[t]])


def make_supervised(y, mode):
    """(X, target, positions) for one transform, over OBSERVED periods only. level: y[t];
    diff: y[t]-y[t-1]; blend: y[t]-trend(t), trend added back at prediction time. A masked
    row is simply absent — that is how the training window is enforced."""
    y = np.asarray(y, dtype=float)
    n = len(y)
    rows, targets, ts = [], [], []
    with _set_view(y):
        z = _model_view(y, mode)
        for t in range(1, n):
            if not np.isfinite(z[t]):
                continue
            if mode == "diff":
                if not np.isfinite(z[t - 1]):
                    continue
                tgt = z[t] - z[t - 1]
            else:
                tgt = z[t]
            rows.append(_feature_row(z, t))
            targets.append(tgt)
            ts.append(t)
    if not rows:
        return np.empty((0, len(FEATURE_NAMES))), np.empty(0), np.empty(0, dtype=int)
    return (np.vstack(rows), np.asarray(targets, dtype=float), np.asarray(ts, dtype=int))


class TrendIndexSelector(BaseEstimator, TransformerMixin):
    """Zeroes the trend index the search did not pick, plus any pruned columns. Zeroing
    rather than dropping keeps FEATURE_NAMES aligned with feature_importances_; a constant
    column is never split on, so a zeroed feature is invisible to the forest."""

    def __init__(self, use_capped=False, drop_idx=()):
        self.use_capped = use_capped
        self.drop_idx = drop_idx

    def fit(self, X, y=None, **kw):
        return self

    def transform(self, X):
        X = np.asarray(X, dtype=float).copy()
        i_raw, i_cap = TREND_COL_IDX.get("t_index"), TREND_COL_IDX.get("t_index_capped")
        if i_raw is not None and i_cap is not None and X.shape[1] > max(i_raw, i_cap):
            X[:, i_raw if self.use_capped else i_cap] = 0.0
        if len(self.drop_idx):
            keep = [i for i in self.drop_idx if i < X.shape[1]]
            if keep:
                X[:, keep] = 0.0
        return X


def recency_enabled():
    return (bool(CONFIG.get("USE_RECENCY_WEIGHTING", False)) if VIEW.recency is None
            else bool(VIEW.recency))


def regime_enabled():
    """Whether the ACTIVE series may use the changepoint dummy (per-series opt-in)."""
    if not CONFIG.get("USE_REGIME_FEATURE", False):
        return False
    return True if VIEW.regime_on is None else bool(VIEW.regime_on)


def prune_idx():
    return tuple(FEATURE_NAMES.index(c) for c in VIEW.prune if c in FEATURE_NAMES)


def recency_weights(pos):
    """DECAY_PER_PERIOD ** (periods before the newest training row); None = unweighted."""
    if not recency_enabled():
        return None
    pos = np.asarray(pos, dtype=float)
    decay = float(DECAY_PER_PERIOD)
    if pos.size == 0 or not (0 < decay < 1):
        return None
    return np.power(decay, np.maximum(float(pos.max()) - pos, 0.0))


def fit_pipe(pipe, X, yv, pos=None):
    """The one place a pipeline is fitted, so recency weighting cannot be half-applied."""
    w = recency_weights(pos) if pos is not None else None
    if w is None or w.shape[0] != np.asarray(yv).shape[0]:
        pipe.fit(X, yv)
    else:
        pipe.fit(X, yv, rf__sample_weight=w)
    return pipe


# Fallback for a window too short to split. It sits INSIDE the search space (leaf 3, not 1),
# so the fallback is a regularised model of the same family as anything the search returns.
DEFAULT_PARAMS = {"rf__n_estimators": 400, "rf__max_depth": 5, "rf__min_samples_leaf": 3,
                  "rf__max_features": 1.0, "sel__use_capped": False}


def make_pipeline(params=None):
    """SimpleImputer -> RandomForestRegressor, pruned columns baked in.

    The imputer is a PIPELINE STEP so its medians are refitted per fold. keep_empty_features
    keeps an all-NaN column (lag_12 can be one at a 24-month window) rather than dropping it
    and silently shortening feature_importances_. n_jobs=1 is deliberate: see Section 8.0.
    """
    pipe = Pipeline([("sel", TrendIndexSelector(drop_idx=prune_idx())),
                     ("impute", SimpleImputer(strategy="median", keep_empty_features=True)),
                     ("rf", RandomForestRegressor(random_state=CONFIG["SEED"], n_jobs=1))])
    pipe.set_params(**(params or DEFAULT_PARAMS))
    return pipe


def _row_predictor(pipe):
    """A one-row predict for the recursion: bit-identical to pipe.predict, ~16x faster.

    RandomForest.predict costs the same for one row as for twelve (19.7ms vs 18.7ms at 400
    trees) because the cost is a per-CALL Python loop over trees - and a recursion is h
    separate one-row calls. Walking the fitted trees directly skips it, in the same order and
    with the same final division, so the result is exact. Self-test (b3) asserts that.
    """
    sel, imp = pipe.named_steps["sel"], pipe.named_steps["impute"]
    trees = [e.tree_ for e in pipe.named_steps["rf"].estimators_]

    def predict_row(x):
        z = np.ascontiguousarray(imp.transform(sel.transform(x)), dtype=np.float32)
        s = trees[0].predict(z)
        for t in trees[1:]:
            s = s + t.predict(z)
        return float((s / len(trees)).reshape(-1)[0])

    return predict_row


def _last_finite_before(y, t):
    seen = np.where(np.isfinite(np.asarray(y, dtype=float))[:t])[0]
    return float(y[seen[-1]]) if seen.size else np.nan


def rf_predict_path(pipe, y_masked, positions, mode):
    """Recursive forecast: each prediction is written back as the next step's lag, which is
    what makes h=12 genuinely harder than h=1. The view (cap, changepoint, blend trend) is
    pinned from TRAINING data first, so a forecast row is built like the training rows."""
    lvl = np.asarray(y_masked, dtype=float).copy()
    if lvl.size < len(CAL_ARR):
        lvl = np.concatenate([lvl, np.full(len(CAL_ARR) - lvl.size, np.nan)])
    preds = np.full(lvl.size, np.nan)
    predict_row = _row_predictor(pipe)
    with _set_view(y_masked):
        work = _model_view(lvl, mode)          # detrended for blend, the level series otherwise
        for t in sorted(int(p) for p in positions):
            raw = predict_row(_feature_row(work, t).reshape(1, -1))
            if mode == "diff":
                prev = (work[t - 1] if t - 1 >= 0 and np.isfinite(work[t - 1])
                        else _last_finite_before(work, t))
                zval = prev + raw if np.isfinite(prev) else np.nan
            else:
                zval = raw
            work[t] = zval
            preds[t] = zval + float(_trend_at(t)) if mode == "blend" else zval
    return preds


def rf_forecast_positions(pipe, y_masked, positions, mode):
    """`rf_predict_path` over a CONTIGUOUS run: every unobserved period between the first and
    last requested position is predicted too, because the recursion needs a value there."""
    positions = sorted({int(p) for p in positions})
    if not positions:
        return np.full(len(CAL_ARR), np.nan)
    y = np.asarray(y_masked, dtype=float)
    lo, hi = positions[0], positions[-1]
    fill = [t for t in range(lo, hi + 1) if t >= len(y) or not np.isfinite(y[t])]
    return rf_predict_path(pipe, y, sorted(set(fill) | set(positions)), mode)

# ---- 7.1  Plausibility screens ----------------------------------------------------------------
# Properties of a forecast path against a history, so they are model-agnostic. A candidate
# that fails is DEMOTED below one that passed, never clipped into looking sane.
def tukey_fence(x, k=1.5):
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if x.size < 4:
        return -np.inf, np.inf
    q1, q3 = np.percentile(x, [25, 75])
    return q1 - k * (q3 - q1), q3 + k * (q3 - q1)


def gap_plausible(path, y_masked, k=1.5, horizon=None, nonneg=False):
    """Screen predictions inside a masked gap. `horizon` bounds how far it looks, because a WF
    mask leaves everything after the origin missing but no fold forecasts past WF12_HORIZON;
    `nonneg` floors the fence at zero, where a negative forecast is a wrong model rather than
    a wide interval. Raises on a gapless series - a silent pass there would disable the guard
    on the production forecast, exactly where it matters most.
    """
    missing = ~np.isfinite(y_masked)
    if not missing.any():
        raise ValueError("gap_plausible() called on a series with no gap - use "
                         "future_plausibility() for the forward horizon instead.")
    obs = y_masked[np.isfinite(y_masked)]
    pos = np.where(missing)[0]
    if horizon is not None and len(pos) > int(horizon):
        pos = pos[:int(horizon)]
    gap = np.asarray(path, dtype=float)[pos]
    if not np.isfinite(gap).all():
        return False
    lo, hi = tukey_fence(obs, k)
    lo, hi = min(lo, obs.min()), max(hi, obs.max())
    if nonneg:
        lo = max(lo, 0.0)
    return bool(gap.min() >= lo and gap.max() <= hi)


def future_plausibility(point, history, k=1.5, verbose=False, nonneg=False):
    """Screen the FORWARD horizon, which gap_plausible() cannot see: each month against the
    observed level distribution, each step from the last actual against the observed
    distribution of same-length steps. A smoke alarm, not a validation."""
    y, p = np.asarray(history, dtype=float), np.asarray(point, dtype=float)
    res = {"level_ok": True, "change_ok": True, "detail": ""}
    if not np.isfinite(p).all():
        return {"level_ok": False, "change_ok": False, "detail": "non-finite forecast",
                "ok": False}
    lo_l, hi_l = tukey_fence(y, k)
    lo_l, hi_l = min(lo_l, y.min()), max(hi_l, y.max())
    if nonneg:
        lo_l = max(lo_l, 0.0)
    if p.min() < lo_l or p.max() > hi_l:
        res["level_ok"] = False
        res["detail"] += (f"level outside [{lo_l:,.0f}, {hi_l:,.0f}] "
                          f"(forecast spans [{p.min():,.0f}, {p.max():,.0f}]); ")
    changes = [y[h:] - y[:-h] for h in range(1, len(p) + 1) if len(y) > h]
    if changes:
        allc = np.concatenate(changes)
        lo_c, hi_c = tukey_fence(allc, k)
        lo_c, hi_c = min(lo_c, allc.min()), max(hi_c, allc.max())
        step = p - y[-1]
        if step.min() < lo_c or step.max() > hi_c:
            res["change_ok"] = False
            res["detail"] += (f"step from last actual outside [{lo_c:,.0f}, {hi_c:,.0f}] "
                              f"(steps span [{step.min():,.0f}, {step.max():,.0f}])")
    res["ok"] = res["level_ok"] and res["change_ok"]
    if verbose and not res["ok"]:
        print("  plausibility flag:", res["detail"])
    return res


def prefer_screened(winners):
    """Candidates, with any that failed the screen demoted below any that passed."""
    clean = [w for w in winners if not w.get("screen_failed", False)]
    return clean if clean else winners


def seasonal_strength_of(v, period=None, context=""):
    """STL seasonal strength on OBSERVED values only. Diagnostic — it gates nothing."""
    period = GM if period is None else int(period)
    v = np.asarray(v, dtype=float)
    v = v[np.isfinite(v)]
    if v.size < 3 * period:
        return np.nan
    try:
        with capture_warnings(f"stl-strength[{context}]"):
            r = STL(pd.Series(v), period=period, robust=True).fit()
        return float(max(0.0, 1 - r.resid.var() / (r.seasonal + r.resid).var()))
    except Exception as e:
        log_failure(f"stl-strength[{context}]", e)
        return np.nan


# ---- 7.1b  Training views and masks ------------------------------------------------------------
# A fold is a CALENDAR cut, not a row count: one monthly mask becomes the periods of the
# active grain that lie WHOLLY inside it, so a weekly and a monthly model at the same origin
# have seen exactly the same days.
def monthly_train_mask(n_months):
    """The first `n_months` USABLE months."""
    m = np.zeros(len(MONTHLY_INDEX), dtype=bool)
    m[np.where(USABLE)[0][:int(n_months)]] = True
    return m


def grain_train_mask(train_mask):
    """Periods falling ENTIRELY inside the training months, by calendar-day allocation, so a
    period straddling the cut is never a training row. The grain no-leakage contract."""
    tr = np.asarray(train_mask, dtype=bool)
    return ALLOC_DAYS[:, :len(tr)][:, tr].sum(axis=1) > 1 - 1e-9


def grain_test_positions(test_mask, train_mask):
    te = np.asarray(test_mask, dtype=bool)
    touch = ALLOC_DAYS[:, :len(te)][:, te].sum(axis=1) > 1e-9
    return np.where(touch & ~grain_train_mask(train_mask))[0]


def grain_masked_values(series_name, train_mask):
    """The only view of the data any model is given, at the active grain."""
    v = GSER[series_name].astype(float).to_numpy().copy()
    v[~grain_train_mask(train_mask)[:len(v)]] = np.nan
    return v


def periods_to_months(period_values, month_mask):
    """Allocate a grain-level path back to calendar months by working-day overlap. A period
    with no value is DROPPED and the months it touched scaled back up by the working days it
    carried — needed because the period straddling history and the forecast is HISTORICAL
    and the forward recursion never predicts it. Self-test (j2) is that bug."""
    p = np.asarray(period_values, dtype=float)
    if p.size < ALLOC.shape[0]:
        p = np.concatenate([p, np.full(ALLOC.shape[0] - p.size, np.nan)])
    mm = np.asarray(month_mask, dtype=bool)
    A = ALLOC[:, :len(mm)][:, mm]
    ok = np.isfinite(p) & (A.sum(axis=1) > 1e-9)
    if not ok.any():
        return np.full(int(mm.sum()), np.nan)
    A_ok = A[ok]
    cov = (A_ok * GCAL_WD[ok, None]).sum(axis=0)      # working days actually supplied
    want = ALL_MONTHS_WD[:len(mm)][mm]                # working days the month really has
    scale = np.where(cov > 1e-9, want / np.where(cov > 1e-9, cov, 1.0), np.nan)
    return (A_ok.T @ p[ok]) * scale



# Real Thai public holidays via the `holidays` package: the lunar Buddhist days and the
# in-lieu substitutions move every year and cannot be a fixed list, so the fixed table is a
# fallback and which source was used is asserted on. Cabinet-declared "bridge" days and
# "Children's Day" are then removed by name: banks shut for them, a manufacturer usually
# does not, and counting them made every walk-forward metric worse.

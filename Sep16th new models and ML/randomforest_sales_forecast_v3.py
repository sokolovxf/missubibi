"""## 4. Target series, calendars and modelling grains

- The hierarchy is complete — total, quantity, top-N categories and an `other` bucket — so
  components sum to the total exactly and Section 12 can reconcile them. Top categories are
  ranked on the **initial training window only**.
- Clipping at zero is disabled for any series that is ever negative: clipping predictions
  while actuals go below zero guarantees an error no model can avoid.
- **4.2** builds working days (Mon–Fri minus real Thai public holidays, lunar ones included).
- **4.3** builds the fortnightly and weekly grains from the same transactions.
- **4.4** builds the customer-signal block (active customers, orders, new-vs-repeat mix),
  exposed to the model only at a **full seasonal-cycle lag**, so every value it reads is
  already known at the forecast origin.
"""

FULL_INDEX = pd.date_range(fy_start(FYS[0]), periods=12 * len(FYS), freq="MS", name="month")


def monthly_series(df, value_col, index, category=None, cat_col=CAT_COL, exclude=None):
    d = (df[df[cat_col] == category] if category is not None else
         df[~df[cat_col].isin(exclude)] if exclude is not None else df)
    s = (d.groupby(pd.Grouper(key="sales_order_date", freq="MS"))[value_col].sum()
         .reindex(index, fill_value=0.0).astype(float))
    s.index.name = "month"
    return s



    print(f"\n=== {name} trial: same folds, same grains, block REMOVED ===", flush=True)
    CONFIG[flag] = False
    res = run_variant(tag=f"no_{flag}", series_names=series_names)
    mase = variant_mase(res[1])
    with_12 = float(np.nanmean([BASE_MASE["WF12"].get(sn, np.nan) for sn in series_dict]))
    wo_12 = float(np.nanmean([mase["WF12"].get(sn, np.nan) for sn in series_dict]))
    with_1 = float(np.nanmean([BASE_MASE["WF1"].get(sn, np.nan) for sn in series_dict]))
    wo_1 = float(np.nanmean([mase["WF1"].get(sn, np.nan) for sn in series_dict]))
    tab = pd.DataFrame({"WF12_with": pd.Series(BASE_MASE["WF12"]),
                        "WF12_without": pd.Series(mase["WF12"]),
                        "WF1_with": pd.Series(BASE_MASE["WF1"]),
                        "WF1_without": pd.Series(mase["WF1"])}).round(3)
    print(f"\n{name}: WF12 pooled MASE at each series' chosen grain\n")
    print(tab.to_string())
    ok, why = wf1_veto(wo_12, with_12, wo_1, with_1, float(CONFIG["TRIAL_MIN_GAIN"]))
    print(f"mean WF12 {with_12:.3f} with vs {wo_12:.3f} without | mean WF1 {with_1:.3f} vs "
          f"{wo_1:.3f} | DROP {'ADOPTED' if ok else 'REJECTED'}: {why}")
    TRIAL_LOG.append({"trial": name, "mean_WF12_with": round(with_12, 3),
                      "mean_WF12_without": round(wo_12, 3), "mean_WF1_with": round(with_1, 3),
                      "mean_WF1_without": round(wo_1, 3),
                      "outcome": "dropped" if ok else "kept", "reason": why})
    if ok:
        BASE_RESULTS, BASE_MASE = res, mase
        note("AUTO-DISABLED", f"{name} switched OFF on measured accuracy: mean WF12 pooled MASE "
                              f"{wo_12:.3f} without it against {with_12:.3f} with it, on the "
                              f"same folds, and WF1 did not contradict it.")
    else:
        CONFIG[flag] = True
        if why.startswith("VETOED"):
            note("SELECTION VETO", f"{name}: dropping the block improved WF12 but hurt WF1, so "
                                   f"it was KEPT. {why}")
    # Rebuild the live feature frame to match whatever CONFIG now says. Without this a
    # REJECTED trial leaves the engine holding the trial's frame, and featset_tag() - which
    # the pruning trial filters its importance rows by - would name the wrong feature set.
    build_feature_frame(verbose=False)
    return ok



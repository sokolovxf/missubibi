def trailing_trend_frac(y_masked, months=12):
    """|OLS slope per MONTH| over the trailing `months` of observed points, over the median.

    Scale-free twice over: dividing by the median makes one threshold work for revenue and
    unit counts alike, and a per-MONTH slope makes it mean the same thing at weekly grain.
    """
    v = np.asarray(y_masked, dtype=float)
    v = v[np.isfinite(v)][-months_to_periods(months):]
    if v.size < 4:
        return np.nan
    med = float(np.median(np.abs(v)))
    if not np.isfinite(med) or med <= 0:
        return np.nan
    slope = float(np.polyfit(np.arange(v.size, dtype=float), v, 1)[0]) * (GM / 12.0)
    return abs(slope) / med




# Split in two so the rule ladder can share work: `score_modes` does all the FITTING and
# depends only on the rules that change a fit (recency, regime dummy); `choose_mode` fits
# nothing and just applies the thresholds. Four of seven profiles differ only in thresholds.
def score_modes(y_masked, series_name, context, horizon=None, params_by_mode=None):
    """Screen and CV-score every target mode under the CURRENT fit-affecting rules."""
    y_masked = np.asarray(y_masked, dtype=float)
    n = len(y_masked)
    v_train = y_masked[np.isfinite(y_masked)]
    has_gap = bool((~np.isfinite(y_masked)).any())
    horizon = months_to_periods(CONFIG["WF12_HORIZON"]) if horizon is None else int(horizon)
    nonneg = bool(SERIES_CLIP.get(series_name, False))
    stats = {"tried": 0, "failed": 0, "implausible": 0, "negative": 0}

    def screen(spec):
        """Fit on the training view, forecast, and ask whether the path is possible."""
        try:
            X, yv, pos = make_supervised(y_masked, spec["mode"])
            if X.shape[0] < 3:
                stats["failed"] += 1
                return True
            pipe = make_pipeline(spec["params"])
            with capture_warnings(f"screen[{context}]"):
                fit_pipe(pipe, X, yv, pos)
        except Exception as e:
            log_failure(f"screen[{context}]", e)
            stats["failed"] += 1
            return True
        try:
            if has_gap:
                missing = np.where(~np.isfinite(y_masked))[0][:horizon]
                path = rf_forecast_positions(pipe, y_masked, missing, spec["mode"])
                if np.any(np.asarray(path)[missing] < 0):
                    stats["negative"] += 1
                ok = gap_plausible(path, y_masked, horizon=horizon, nonneg=nonneg)
            else:
                fut = list(range(n, n + horizon))
                path = rf_forecast_positions(pipe, y_masked, fut, spec["mode"])
                pt = np.asarray(path)[n:n + horizon]
                if np.any(pt < 0):
                    stats["negative"] += 1
                ok = future_plausibility(pt, v_train, nonneg=nonneg)["ok"]
        except Exception as e:
            log_failure(f"screen-path[{context}]", e)
            stats["failed"] += 1
            return True
        if not ok:
            stats["implausible"] += 1
        return not ok

    winners = []
    for mode in CONFIG["RF_TARGET_MODES"]:
        stats["tried"] += 1
        frozen = (params_by_mode or {}).get(mode)
        if frozen is None:
            params, tune_mae = tune_rf(y_masked, mode, f"{context}|{mode}")
        else:
            params, tune_mae = dict(frozen["params"]), float(frozen.get("tune_mae", np.nan))
        spec = {"mode": mode, "params": params, "tune_mae": tune_mae,
                "exog_wd": USE_WD_FEATURES}
        spec["screen_failed"] = bool(screen(spec))
        winners.append(spec)
    for w in prefer_screened(winners):
        w["cv_mae"], w["cv_bias"], w["cv_bias_se"] = rf_cv_rolling_stats(
            y_masked, w, f"{context}|{w['mode']}")
    return {"winners": winners, "stats": stats, "has_gap": has_gap,
            "seasonal": seasonal_strength_of(v_train, GM, context)}


def choose_mode(scored, y_masked, series_name, context, rules=None):
    """Pick the target transform and estimate its bias correction. No fitting happens here.

    `rules` is the per-series profile: whether the trend-based push away from `level` may
    overrule held-out error at all, and the three thresholds that govern it.
    """
    rules = dict(rules or {"force": True})
    y_masked = np.asarray(y_masked, dtype=float)
    v_train = y_masked[np.isfinite(y_masked)]
    winners = [dict(w) for w in scored["winners"]]
    stats = scored["stats"]
    ranked = prefer_screened(winners)
    best, mode_raw = None, None
    if ranked:
        scored_w = [w for w in ranked if np.isfinite(w.get("cv_mae", np.nan))]
        if scored_w:
            best = min(scored_w, key=lambda w: w["cv_mae"])
            mode_raw = best["mode"]          # what held-out error ALONE would have chosen
            by_mode = {w["mode"]: w for w in scored_w}
            lvl = by_mode.get("level")
            alts = [by_mode[m] for m in EXTRAP_MODES if m in by_mode]
            # On a short window two modes' held-out errors are usually within noise and `min`
            # settles a coin flip; where the trailing months have a real slope the tie breaks
            # on the one thing that is not noise - a level target cannot leave its training
            # range. Ties only, and refused when the challenger is worse by more than
            # FORCE_MAX_PENALTY_PCT: a steep trend distrusts a CLOSE margin, not a wide one.
            if alts and lvl is not None and best["mode"] == "level" and rules.get("force", True):
                alt = min(alts, key=lambda w: w["cv_mae"])
                tb_pct = float(rules.get("tb", CONFIG.get("BIAS_TIEBREAK_PCT", 0.0)) or 0.0)
                s_min = float(rules.get("smin", CONFIG["TREND_SLOPE_MIN_FRAC"]))
                s_force = float(rules.get("sforce", CONFIG["TREND_SLOPE_FORCE_FRAC"]))
                pen_max = float(rules.get("pen", CONFIG["FORCE_MAX_PENALTY_PCT"]))
                e_l, e_d = float(lvl["cv_mae"]), float(alt["cv_mae"])
                denom = min(abs(e_l), abs(e_d))
                within = (tb_pct > 0 and np.isfinite(denom) and denom > 0
                          and 100.0 * abs(e_d - e_l) / denom <= tb_pct)
                tfrac = trailing_trend_frac(y_masked, months=12)
                trending = np.isfinite(tfrac) and tfrac > s_min
                penalty_ok = (abs(e_l) <= 0 or 100.0 * (e_d - e_l) / abs(e_l) <= pen_max)
                steep = np.isfinite(tfrac) and tfrac > s_force
                forced = steep and penalty_ok
                if steep and not penalty_ok:
                    with _LOG_LOCK:
                        FORCE_REFUSED_ROWS.append({
                            "series": series_name, "context": context,
                            "cv_mae_level": round(e_l, 4), "cv_mae_alt": round(e_d, 4),
                            "alt_mode": alt["mode"],
                            "penalty_%": round(100.0 * (e_d - e_l) / abs(e_l), 1),
                            "trend_slope_over_median": round(float(tfrac), 4)})
                if forced or (within and trending):
                    best = alt
                    with _LOG_LOCK:
                        TIEBREAK_ROWS.append({
                            "series": series_name, "context": context,
                            "rule": "forced (steep trend)" if forced else "tie-break (close CV)",
                            "cv_mae_level": round(e_l, 4), "cv_mae_alt": round(e_d, 4),
                            "gap_%": round(100.0 * abs(e_d - e_l) / denom, 2) if denom > 0 else np.nan,
                            "trend_slope_over_median": round(float(tfrac), 4),
                            "switched": f"level -> {alt['mode']}"})
        else:
            # No held-out evidence at all: fall back to the one-step tuning score and say so by
            # leaving cv_mae NaN.
            usable = [w for w in ranked if np.isfinite(w.get("tune_mae", np.nan))]
            best = min(usable, key=lambda w: w["tune_mae"]) if usable else ranked[0]

    # Bias correction: a share of this configuration's own held-out mean error, shrunk by
    # b^2/(b^2+se^2) so a bias large next to its own noise is applied nearly in full, then
    # capped at a share of the level - beyond that it is a level shift, not a tilt.
    if best is not None:
        b, se = float(best.get("cv_bias", np.nan)), float(best.get("cv_bias_se", np.nan))
        if CONFIG["BIAS_CORRECTION"] and np.isfinite(b):
            # A non-finite se means NO correction, not a full one: a bias measured on one
            # rolling origin deserves the least trust, not the most.
            shrink = 0.0 if not np.isfinite(se) else (1.0 if se <= 0 else b * b / (b * b + se * se))
            best["bias_shrink"] = float(shrink)
            adj = float(CONFIG["BIAS_CORRECTION_WEIGHT"]) * b * shrink
            lvl_mean = float(np.mean(np.abs(v_train))) if v_train.size else 0.0
            cap = float(CONFIG.get("BIAS_CORRECTION_MAX_FRAC", np.inf)) * lvl_mean
            if np.isfinite(cap) and abs(adj) > cap:
                best["bias_capped"] = True
                adj = float(np.sign(adj) * cap)
            best["bias_adj"] = adj
        else:
            best["bias_shrink"] = best["bias_adj"] = 0.0

    if best is None:
        best = {"mode": "level", "params": dict(DEFAULT_PARAMS), "exog_wd": USE_WD_FEATURES,
                "tune_mae": np.nan, "cv_mae": np.nan, "screen_failed": True, "bias_adj": 0.0}
        log_failure(f"select[{context}]",
                    RuntimeError("every candidate failed; falling back to RF(level) defaults"))
    best["mode_raw"] = mode_raw if mode_raw is not None else best.get("mode")
    best.update({"n_candidates": stats["tried"], "n_failed": stats["failed"],
                 "n_implausible": stats["implausible"], "n_negative": stats["negative"],
                 "screen": "gap" if scored["has_gap"] else "future",
                 "n_groups": len(CONFIG["RF_TARGET_MODES"]),
                 "seasonal_strength_train": scored["seasonal"]})
    best.setdefault("screen_failed", False)
    for k in ("cv_mae", "cv_bias", "cv_bias_se", "tune_mae"):
        best.setdefault(k, np.nan)
    for k in ("bias_shrink", "bias_adj"):
        best.setdefault(k, 0.0)
    best.setdefault("bias_capped", False)
    return best


def select_rf_spec(y_masked, series_name, context, horizon=None, params_by_mode=None,
                   rules=None):
    """Score every target mode on held-out error, then choose one. See Section 0."""
    sc = score_modes(y_masked, series_name, context, horizon=horizon,
                     params_by_mode=params_by_mode)
    return choose_mode(sc, y_masked, series_name, context, rules)

# ---- 7.4b  Per-series hyperparameters and rule profiles, frozen once and cached -------------
# Both are chosen on the EARLIEST validated training window and reused unchanged everywhere
# after - leak-free, because every later fold's training window CONTAINS it. Cached to disk
# under a hash of what they depend on, so a re-run skips finished searches and a changed
# grid invalidates them.
HPARAM_CACHE, HPARAM_ROWS, RULE_CACHE, RULE_ROWS = {}, [], {}, []
SERIES_PRUNE = {}          # series -> feature names zeroed out (decided in Section 8.5)


@contextlib.contextmanager
def _apply_rules(rules):
    """Install a rule profile for the duration of a fit. Restored afterwards, always."""
    prev = (VIEW.recency, VIEW.regime_on)
    VIEW.recency = bool(rules.get("recency", True))
    VIEW.regime_on = bool(rules.get("regime", False))
    try:
        yield rules
    finally:
        VIEW.recency, VIEW.regime_on = prev


@contextlib.contextmanager
def _apply_prune(series_name):
    prev = VIEW.prune
    VIEW.prune = tuple(SERIES_PRUNE.get(series_name, ()))
    try:
        yield VIEW.prune
    finally:
        VIEW.prune = prev


def _profiles():
    """The candidate ladder: the default, each rule flipped one at a time, everything off,
    then two variants of the trend-threshold triple. Not a cross product — a handful of
    candidates scored on ~24 months of held-out error is already a lot of selection."""
    base = dict(recency=bool(CONFIG["USE_RECENCY_WEIGHTING"]), force=True, regime=False,
                tb=float(CONFIG["BIAS_TIEBREAK_PCT"]),
                smin=float(CONFIG["TREND_SLOPE_MIN_FRAC"]),
                sforce=float(CONFIG["TREND_SLOPE_FORCE_FRAC"]),
                pen=float(CONFIG["FORCE_MAX_PENALTY_PCT"]))
    P = [dict(base, name="default"),
         dict(base, name="no_recency", recency=False),
         dict(base, name="no_force", force=False),
         dict(base, name="regime", regime=True),
         dict(base, name="plain", recency=False, force=False),
         dict(base, name="force_soft", tb=12.0, smin=0.010, sforce=0.025),
         dict(base, name="force_hard", tb=2.0, smin=0.040, sforce=0.080)]
    return P[:4] if QUICK_MODE else P


RULE_PROFILES = _profiles()
DEFAULT_RULES = dict(RULE_PROFILES[0])


def series_hparams(series_name):
    """Frozen {mode: {"params", "tune_mae"}} for this series at the ACTIVE grain.

    Keyed on series and grain but NOT on the feature set: the Section 8 trials hold the
    hyperparameters fixed while they change one feature block, so each trial is an A/B on that
    block rather than two changes at once - and it is most of the runtime they would repeat.
    """
    key = (series_name, GRAIN)
    if key in HPARAM_CACHE:
        return HPARAM_CACHE[key]
    with _key_lock(key):
        if key in HPARAM_CACHE:
            return HPARAM_CACHE[key]
        ref = int(CONFIG["MIN_TRAIN_MONTHS"])
        y = grain_masked_values(series_name, monthly_train_mask(ref))
        dkey = cache_key("hp", series_name, GRAIN, ref,
                         CONFIG["RF_PARAM_GRID"], CONFIG["RF_SEARCH"], CONFIG["RF_N_ITER"],
                         CONFIG["RF_TUNE_SPLITS"], CONFIG["SEED"],
                         list(CONFIG["RF_TARGET_MODES"]), CONFIG["USE_RECENCY_WEIGHTING"],
                         CONFIG["RECENCY_DECAY"], arr_hash(y))
        hit = cache_get(dkey)
        if hit is not None:
            out = {m: {"params": dict(v["params"]), "tune_mae": v["tune_mae"]}
                   for m, v in hit.items()}
        else:
            out = {}
            for mode in CONFIG["RF_TARGET_MODES"]:
                # Tuned under the DEFAULT profile: the rule profile is chosen AFTER the
                # hyperparameters, using them, so it cannot also be an input to them.
                with _apply_rules(DEFAULT_RULES):
                    params, mae = tune_rf(y, mode, f"{series_name}|{GRAIN}|freeze@{ref}m")
                out[mode] = {"params": params,
                             "tune_mae": float(mae) if np.isfinite(mae) else None}
            cache_put(dkey, out)
        with _LOG_LOCK:
            for mode, v in out.items():
                p = v["params"]
                HPARAM_ROWS.append({"series": series_name, "grain": GRAIN,
                                    "featset": featset_tag(), "mode": mode,
                                    "n_estimators": p.get("rf__n_estimators"),
                                    "max_depth": p.get("rf__max_depth"),
                                    "min_samples_leaf": p.get("rf__min_samples_leaf"),
                                    "max_features": p.get("rf__max_features"),
                                    "use_capped": p.get("sel__use_capped"),
                                    "tune_mae": v["tune_mae"], "frozen_on_months": ref})
        out = {m: {"params": v["params"],
                   "tune_mae": np.nan if v["tune_mae"] is None else float(v["tune_mae"])}
               for m, v in out.items()}
        HPARAM_CACHE[key] = out
        return out


def series_rules(series_name):
    """The rule profile this series earned at the ACTIVE grain, on its OWN held-out CV MAE.
    Held fixed across the feature trials for the same reason as the hyperparameters."""
    key = (series_name, GRAIN)
    if key in RULE_CACHE:
        return RULE_CACHE[key]
    with _key_lock(("rules",) + key):
        if key in RULE_CACHE:
            return RULE_CACHE[key]
        default = dict(DEFAULT_RULES)
        if not CONFIG.get("PER_SERIES_RULES", False):
            RULE_CACHE[key] = default
            return default
        ref = int(CONFIG["MIN_TRAIN_MONTHS"])
        y = grain_masked_values(series_name, monthly_train_mask(ref))
        hp = series_hparams(series_name)
        dkey = cache_key("rules", series_name, GRAIN, ref,
                         [p["name"] for p in RULE_PROFILES], RULE_PROFILES,
                         CONFIG["RULE_SELECT_MIN_GAIN"], CONFIG["CV_HORIZON"],
                         CONFIG["CV_ORIGINS"], CONFIG["CV_MIN_TRAIN_MONTHS"],
                         list(CONFIG["RF_TARGET_MODES"]), arr_hash(y),
                         {m: v["params"] for m, v in hp.items()})
        hit = cache_get(dkey)
        if hit is not None:
            pick, rows = dict(hit["pick"]), list(hit["rows"])
        else:
            # Profiles that differ ONLY in the trend thresholds produce identical fits, so the
            # ladder is grouped by what actually changes a fit — recency weighting and the
            # regime dummy — and each group is screened and CV-scored once. Seven profiles
            # cost three scoring passes instead of seven.
            scored, rows = [], []
            groups = {}
            for prof in RULE_PROFILES:
                groups.setdefault((bool(prof["recency"]), bool(prof["regime"])), []).append(prof)
            for (rec, reg), profs in groups.items():
                with _apply_rules({"recency": rec, "regime": reg}):
                    sc = score_modes(y, series_name,
                                     f"{series_name}|{GRAIN}|rules|r{int(rec)}g{int(reg)}",
                                     params_by_mode=hp)
                    for prof in profs:
                        spec = choose_mode(sc, y, series_name,
                                           f"{series_name}|{GRAIN}|rules|{prof['name']}", prof)
                        cv = float(spec.get("cv_mae", np.nan))
                        scored.append({"profile": prof, "cv_mae": cv})
                        rows.append({"series": series_name, "grain": GRAIN,
                                     "featset": featset_tag(), "profile": prof["name"],
                                     "recency": prof["recency"], "force": prof["force"],
                                     "regime": prof["regime"],
                                     "cv_mae": None if not np.isfinite(cv) else cv,
                                     "mode_chosen": spec.get("mode")})
            usable = [r for r in scored if np.isfinite(r["cv_mae"])]
            pick = default
            if usable:
                base = next((r for r in usable if r["profile"]["name"] == "default"), None)
                best = min(usable, key=lambda r: r["cv_mae"])
                if base is None:
                    pick = best["profile"]
                else:
                    gain = (base["cv_mae"] - best["cv_mae"]) / max(abs(base["cv_mae"]), 1e-12)
                    pick = (best["profile"] if gain >= float(CONFIG["RULE_SELECT_MIN_GAIN"])
                            else base["profile"])
            pick = dict(pick)
            cache_put(dkey, {"pick": pick, "rows": rows})
        for r in rows:
            r["chosen"] = (r["profile"] == pick["name"])
            r["cv_mae"] = np.nan if r["cv_mae"] is None else float(r["cv_mae"])
        with _LOG_LOCK:
            RULE_ROWS.extend(rows)
        RULE_CACHE[key] = pick
        return pick


# ---- 7.4c  The configuration used at a walk-forward origin -------------------------------------
# Hyperparameters and the rule profile are frozen per series; what still refreshes every
# MODEL_REFRESH_MONTHS is what depends on how much history the fold has - the target
# transform and the bias correction. The reference window always ends at or before the origin.
def wf_spec_for(series_name, origin):
    mt, rf = int(CONFIG["MIN_TRAIN_MONTHS"]), int(CONFIG["MODEL_REFRESH_MONTHS"])
    n_us = int(USABLE[:origin].sum()) if origin is not None else int(USABLE.sum())
    ref = mt + max(0, (n_us - mt) // rf) * rf
    key = (series_name, GRAIN, featset_key(), "WF", ref)
    if key not in SPEC_CACHE:
        with _key_lock(key):
            if key not in SPEC_CACHE:
                hp, rules = series_hparams(series_name), series_rules(series_name)
                y = grain_masked_values(series_name, monthly_train_mask(ref))
                with _apply_rules(rules):
                    spec = select_rf_spec(y, series_name, f"{series_name}|{GRAIN}|WF@{ref}m",
                                          params_by_mode=hp, rules=rules)
                spec["rules"], spec["grain"] = dict(rules), GRAIN
                SPEC_CACHE[key] = spec
    return SPEC_CACHE[key], ref


# ---- 7.5  The fold runners -----------------------------------------------------------------------
def rf_fold(s, train_mask, test_mask, series_name, spec=None, context=""):
    """One code path for every scheme and grain, because everything outside train_mask is NaN: an
    interior gap is forecast straight across, a trailing gap reduces to an h-step forecast. The
    path is produced at the ACTIVE grain and converted back to calendar months before it leaves,
    so the rest of the notebook only ever sees monthly, comparable numbers.
    """
    with _apply_prune(series_name):
        y = grain_masked_values(series_name, train_mask)
        tr_p = grain_train_mask(train_mask)
        te = np.asarray(test_mask, bool)
        n_months = int(te.sum())
        rules = (spec or {}).get("rules") or series_rules(series_name)
        if spec is None:            # LOFO and any per-fold path
            with _apply_rules(rules):
                spec = select_rf_spec(y, series_name, context,
                                      params_by_mode=series_hparams(series_name), rules=rules)
                spec["rules"] = dict(rules)
        try:
            with _apply_rules(rules):
                X, yv, pos = make_supervised(y, spec["mode"])
                if X.shape[0] < 3:
                    raise ValueError(f"only {X.shape[0]} usable training rows for "
                                     f"mode={spec['mode']}")
                pipe = make_pipeline(spec["params"])
                with capture_warnings(f"fit[{context}]"):
                    fit_pipe(pipe, X, yv, pos)
                parts = context.split("|")
                _record_importance(pipe, series_name, parts[1] if len(parts) > 1 else "?",
                                   spec["mode"], context)
                path = rf_forecast_positions(pipe, y, grain_test_positions(test_mask, train_mask),
                                             spec["mode"])
            # The bias correction is an OUT-OF-SAMPLE adjustment, so it is applied only
            # outside the training window; its size came from training data alone.
            adj = float(spec.get("bias_adj", 0.0) or 0.0)
            if adj:
                path = np.asarray(path, dtype=float).copy()
                outside = np.ones(path.size, dtype=bool)
                outside[:len(tr_p)] = ~tr_p
                path[outside] = path[outside] + adj
            fitted, status = periods_to_months(path, test_mask), "ok"
        except Exception as e:
            log_failure(f"fit[{context}] {spec_label(spec)}", e)
            fitted, status = np.full(n_months, np.nan), f"failed:{type(e).__name__}"
        return postprocess(fitted, series_name, context, model="RandomForest"), spec, status


def seasonal_naive_fold(s, train_mask, test_mask, series_name, period=M):
    y = masked_values(s, train_mask)
    work, preds = y.copy(), np.full(len(y), np.nan)
    for pos in np.where(np.asarray(test_mask, bool))[0]:
        val, ref = np.nan, pos - period
        while ref >= 0:
            if np.isfinite(work[ref]):
                val = work[ref]
                break
            ref -= period
        if not np.isfinite(val):
            seen = np.where(np.isfinite(work[:pos]))[0]
            if len(seen):
                val = work[seen[-1]]
        preds[pos] = work[pos] = val
    te = np.asarray(test_mask, bool)
    status = "ok" if np.isfinite(preds[te]).all() else "insufficient_history"
    return postprocess(preds[te], series_name, "snaive", model="SeasonalNaive"), status


# ---- 7.6  Self-tests: no leakage, real recursion, and the extrapolation limit ---------------------
# Every test runs at EVERY candidate grain: the weekly path is the same code with different
# globals, and the only honest way to say so is to point the same assertions at all of them.
def selftest(grain=None):
    if grain is not None:
        set_grain(grain)
    rng = np.random.default_rng(0)
    n = N_PERIODS
    t = np.arange(n, dtype=float)
    H = months_to_periods(12)
    truth = 100 + 2 * (12.0 / GM) * t + 10 * np.sin(2 * np.pi * t / GM) + rng.normal(0, 2, n)

    # (a) THE leakage test. A feature row at t must be a function of y[:t] alone, so replacing
    #     y[t:] with anything must leave it bit-identical. Run twice — bare, and under a pinned
    #     training view, because t_index_capped, regime_step and the blend trend are the
    #     columns that read the training window rather than the calendar.
    tpos = int(min(n - 2, MAX_LAG + 5))
    wild = truth.copy()
    wild[tpos:] = -1e9
    assert np.allclose(_feature_row(truth, tpos), _feature_row(wild, tpos), equal_nan=True), \
        "a feature row read the value it is predicting"
    view = truth.copy()
    view[tpos:] = np.nan
    with _set_view(view):
        assert np.allclose(_feature_row(truth, tpos), _feature_row(wild, tpos), equal_nan=True), \
            "a feature row read the future once a training view was pinned"
        cap_here, reg_here, trend_here = VIEW.cap, VIEW.regime, VIEW.trend
    # and the pinned view itself must not move when the masked tail changes
    with _set_view(view):
        v1 = (VIEW.cap, VIEW.regime, VIEW.trend)
    w_view = wild.copy()
    w_view[tpos:] = np.nan
    with _set_view(w_view):
        assert (VIEW.cap, VIEW.regime, VIEW.trend) == v1, \
            "the pinned training view depends on masked-out values"
    print(f"(a) no leakage: feature row at t={tpos} unchanged when y[{tpos}:] becomes -1e9, "
          f"bare and under a pinned view (cap={cap_here}, break={reg_here}, "
          f"trend slope={trend_here[0]:.3f}; {len(FEATURE_NAMES)} features)")

    # (a2) the changepoint must be READ FROM THE TRAINING VIEW, never the whole series.
    step = np.concatenate([np.full(n // 2, 100.0), np.full(n - n // 2, 200.0)]) + rng.normal(0, 2, n)
    cp_all = detect_changepoint(step, min_seg=max(3, months_to_periods(3)))
    hidden = step.copy()
    hidden[n // 2:] = np.nan
    assert cp_all is not None and abs(cp_all - n // 2) <= max(2, months_to_periods(1)), \
        f"a 2x level shift at t={n // 2} was not detected (got {cp_all})"
    assert detect_changepoint(hidden, min_seg=max(3, months_to_periods(3))) is None, \
        "a changepoint was detected inside the masked tail - the detector reads the future"
    print(f"(a2) changepoint detector finds the 2x step at t={cp_all} and finds NOTHING when "
          f"it is masked out of the training view")

    # (a3) THE GRAIN leakage test: a training period must contain no day the fold was not given.
    tr_m = monthly_train_mask(CONFIG["MIN_TRAIN_MONTHS"])
    cut = MONTHLY_INDEX[int(np.where(tr_m)[0][-1]) + 1]
    p_start, p_end = grain_edges(CAL_INDEX, GRAIN)
    tr_p = grain_train_mask(tr_m)
    assert bool((p_end[:len(tr_p)][tr_p] <= cut).all()), \
        f"a training period at grain {GRAIN} extends past the fold cut {cut.date()}"
    te_m = np.zeros(len(MONTHLY_INDEX), bool)
    _o = int(np.where(tr_m)[0][-1]) + 1
    te_m[_o:_o + CONFIG["WF12_HORIZON"]] = True
    te_p = grain_test_positions(te_m, tr_m)
    assert len(te_p) and not set(te_p) & set(np.where(tr_p)[0]), \
        "a period is both a training row and a test row"
    print(f"(a3) grain {GRAIN}: {int(tr_p.sum())} training periods all END on or before "
          f"{cut.date()}; {len(te_p)} disjoint test periods span the horizon")

    # (b) the supervised matrix must carry each target transform exactly and reconstruct.
    Xl, yl, tl = make_supervised(truth, "level")
    Xd, yd, td = make_supervised(truth, "diff")
    Xb, yb, tb = make_supervised(truth, "blend")
    assert np.allclose(yl, truth[tl]), "level target is not y[t]"
    assert np.allclose(yd, truth[td] - truth[td - 1]), "diff target is not y[t] - y[t-1]"
    assert np.allclose(truth[td - 1] + yd, truth[td]), "diff target does not reconstruct"
    with _set_view(truth):
        _tr = _trend_at(tb)
    assert np.allclose(yb, truth[tb] - _tr), "blend target is not y[t] - trend(t)"
    assert np.allclose(yb + _tr, truth[tb]), "blend target does not reconstruct the level"
    print(f"(b) supervised matrix: level {Xl.shape}, diff {Xd.shape}, blend {Xb.shape}; "
          f"diff and blend targets both reconstruct the level exactly")

    # (b2) the recursion must never peek, and must genuinely chain.
    cut_p = n - H
    y_mask = truth.copy()
    y_mask[cut_p:] = np.nan
    Xf, yf, _ = make_supervised(y_mask, "level")
    pipe_b = make_pipeline({**DEFAULT_PARAMS, "rf__n_estimators": 100})
    with capture_warnings("selftest"):
        pipe_b.fit(Xf, yf)
    p1 = rf_forecast_positions(pipe_b, y_mask, range(cut_p, n), "level")[cut_p:n]
    p2 = rf_forecast_positions(pipe_b, y_mask.copy(), range(cut_p, n), "level")[cut_p:n]
    assert np.allclose(p1, p2), "the recursive path is not deterministic on the masked view"
    work, manual = y_mask.copy(), []
    with _set_view(y_mask):
        for tt in range(cut_p, n):
            v = float(pipe_b.predict(_feature_row(work, tt).reshape(1, -1))[0])
            manual.append(v)
            work[tt] = v
        cheat = float(pipe_b.predict(_feature_row(truth, cut_p + 1).reshape(1, -1))[0])
    assert np.allclose(p1, manual), "rf_forecast_positions does not match a manual recursion"
    print(f"(b2) recursion is genuine: h=2 from its own h=1 prediction is {p1[1]:,.1f}; handed "
          f"the ACTUAL period-{cut_p} value it would say {cheat:,.1f}")

    # (b3) the fast one-row predictor the recursion uses must be EXACT, not merely close:
    #      a recursion feeds its own output back in, so a rounding difference would compound.
    _pr = _row_predictor(pipe_b)
    _rows = [_feature_row(y_mask, tt).reshape(1, -1) for tt in range(cut_p - 6, cut_p)]
    _fast = [_pr(r) for r in _rows]
    _ref = [float(pipe_b.predict(r)[0]) for r in _rows]
    assert _fast == _ref, "the fast one-row predictor does not match pipe.predict bit for bit"
    print(f"(b3) the recursion's fast one-row predictor is bit-identical to pipe.predict "
          f"over {len(_rows)} rows")

    # (c) gap_plausible must refuse a gapless series instead of silently passing.
    try:
        gap_plausible(truth, truth)
        raise AssertionError("gap_plausible accepted a gapless series - the guard is disabled")
    except ValueError:
        print("(c) gap_plausible REFUSES a gapless series (a silent pass would disable the "
              "guard exactly on the production forecast)")

    # (c2) the gap screen must judge only as far as the fold actually forecasts.
    cut2 = n - 2 * H
    y3 = truth.copy()
    y3[cut2:] = np.nan
    tail_wild = truth.copy()
    tail_wild[cut2:cut2 + H] = truth[cut2 - 1]
    tail_wild[cut2 + H:] = 1e6
    assert gap_plausible(tail_wild, y3, horizon=H), "the bounded screen looked past the horizon"
    assert not gap_plausible(tail_wild, y3), "the unbounded screen missed a runaway tail"
    print(f"(c2) gap screen bounded to the forecast horizon ({2 * H}-period mask, {H}-period check)")

    # (c3) on a never-negative series a path that dives below zero must be REFUSED at
    #      selection, not repaired by the clip afterwards.
    wide = np.linspace(11.0, 71.0, n)
    y4 = wide.copy()
    y4[cut_p:] = np.nan
    lo_fence = tukey_fence(y4[np.isfinite(y4)])[0]
    dive = wide.copy()
    dive[cut_p:] = -5.0
    assert lo_fence < 0 and gap_plausible(dive, y4, nonneg=False), "test setup"
    assert not gap_plausible(dive, y4, nonneg=True), \
        "a negative path passed the screen on a non-negative series"
    assert not future_plausibility(np.full(H, -5.0), y4[np.isfinite(y4)], nonneg=True)["level_ok"]
    print(f"(c3) non-negative series: the plain Tukey fence is {lo_fence:,.1f} and licenses a "
          f"negative forecast; nonneg=True refuses it")

    # (d) future_plausibility must catch a runaway forward forecast.
    good, bad = future_plausibility(truth[-H:] * 1.02, truth), future_plausibility(truth[-H:] * 50, truth)
    assert good["ok"] and not bad["ok"]
    print(f"(d) future_plausibility: sane ok={good['ok']}, 50x ok={bad['ok']}")

    # (e3) a screen-failed candidate must not beat one that passed, but must survive alone.
    w_ok, w_bad = {"tag": "ok", "screen_failed": False}, {"tag": "bad", "screen_failed": True}
    assert prefer_screened([w_bad, w_ok]) == [w_ok], "a screen-failed candidate still competes"
    assert prefer_screened([w_bad]) == [w_bad], "the fallback vanished when it was all we had"
    print("(e3) a screen-failed target mode is demoted below a plausible one")

    # (e5) the inner CV must run at the SHORTEST window any fold uses, or the target-mode
    #      choice, the rule profile and the bias correction are all silently off where history
    #      is thinnest.
    mt, cvm = months_to_periods(CONFIG["MIN_TRAIN_MONTHS"]), months_to_periods(CONFIG["CV_MIN_TRAIN_MONTHS"])
    Hcv, no = months_to_periods(CONFIG["CV_HORIZON"]), CONFIG["CV_ORIGINS"]
    assert cvm < mt, "the inner CV floor must be below MIN_TRAIN_MONTHS or it cannot run there"
    origins_at_min = sum(1 for j in range(no) if mt - (Hcv + j) >= cvm)
    assert origins_at_min > 1, ("the inner CV cannot produce a standard error at "
                                "MIN_TRAIN_MONTHS - the bias correction would never fire")
    print(f"(e5) at the {CONFIG['MIN_TRAIN_MONTHS']}-month minimum window the inner CV gets "
          f"{origins_at_min} of {no} rolling origins (floor {cvm} periods)")

    # (f) THE structural limit, and the reason diff and blend are offered at all. A level
    #     target can never output a value below the smallest period it trained on; on a
    #     declining series it is pinned above the trend. diff compounds a negative step;
    #     blend extrapolates a fitted line. Both must be able to leave the training range.
    decl = 3000.0 - 40.0 * (12.0 / GM) * t + rng.normal(0, 15, n)
    y5 = decl.copy()
    y5[cut_p:] = np.nan
    floor = float(np.nanmin(y5))
    outs = {}
    for mode in ("level", "diff", "blend"):
        Xm, ym, _ = make_supervised(y5, mode)
        pm = make_pipeline({**DEFAULT_PARAMS, "rf__n_estimators": 200})
        with capture_warnings("selftest"):
            pm.fit(Xm, ym)
        outs[mode] = rf_forecast_positions(pm, y5, range(cut_p, n), mode)[n - 1]
    print(f"(f) declining series, h={n - cut_p} periods: level={outs['level']:,.0f}, "
          f"diff={outs['diff']:,.0f}, blend={outs['blend']:,.0f}; smallest TRAINING period is "
          f"{floor:,.0f}, true value is {decl[n - 1]:,.0f}")
    assert outs["level"] >= floor - 1e-6, \
        "a level-target forest predicted below its smallest training target - impossible"
    assert outs["diff"] < floor, "the diff target could not follow the trend below the floor"
    assert outs["blend"] < floor, "the blend target could not follow the trend below the floor"

    # (g) the calendar features must be present and switchable.
    assert ("working_days" in CAL_COLS) == bool(CONFIG["USE_WORKING_DAYS"]), \
        "USE_WORKING_DAYS does not control whether the regressor is built"
    assert ("regime_step" in FEATURE_NAMES) == bool(CONFIG.get("USE_REGIME_FEATURE", False)), \
        "USE_REGIME_FEATURE does not control whether the step dummy is built"
    assert len(_feature_row(truth, tpos)) == len(FEATURE_NAMES), "feature row length mismatch"
    assert len({*FEATURE_NAMES}) == len(FEATURE_NAMES), "duplicate feature name"
    print(f"(g) calendar block = {CAL_COLS}")

    # (h) ALIGNMENT: every column must be the quantity its NAME claims. Different bug from
    #     (a): a lag silently reading y[t-2] into 'lag_1' passes (a) and still degrades every
    #     forecast and every importance table. Asserted as an exact identity, not via "lag_1
    #     should be most important" — impurity importance is biased toward continuous columns.
    fr = pd.Series(_feature_row(truth, tpos), index=FEATURE_NAMES)
    for L in LAGS:
        assert fr[f"lag_{L}"] == truth[tpos - L], f"column lag_{L} is not y[t-{L}]"
    for L in DIFF_LAGS:
        assert np.isclose(fr[f"dlag_{L}"], truth[tpos - L] - truth[tpos - L - 1]), \
            f"column dlag_{L} is not the first difference at t-{L}"
    for W in ROLLS:
        assert np.isclose(fr[f"rmean_{W}"], truth[tpos - W:tpos].mean()), \
            f"column rmean_{W} is not the mean of the {W} periods BEFORE t"
        assert np.isclose(fr[f"rstd_{W}"], truth[tpos - W:tpos].std(ddof=1)), \
            f"column rstd_{W} is not the sd of the {W} periods BEFORE t"
    assert np.isclose(fr[f"yoy_momentum_{YOY_K}"],
                      truth[tpos - YOY_K:tpos].mean()
                      / truth[tpos - GM - YOY_K:tpos - GM].mean() - 1.0), "yoy_momentum is wrong"
    if "t_index" in FEATURE_NAMES:
        assert fr["t_index"] == tpos, "t_index is not the position in the series"
    if "month_num" in FEATURE_NAMES:
        assert fr["month_num"] == CAL_INDEX[tpos].month, "month_num is off by a period"
    print(f"(h) every column equals its definition at t={tpos} ({CAL_INDEX[tpos]:%Y-%m-%d}): "
          f"lag_{LAGS[0]}={fr[f'lag_{LAGS[0]}']:,.1f}, lag_{GM}={fr[f'lag_{GM}']:,.1f}, "
          f"rmean_{ROLLS[0]}={fr[f'rmean_{ROLLS[0]}']:,.1f}, month_num={fr['month_num']:.0f}")

    # (h2) importances must be a valid distribution — Sections 9 and 12 report them as shares.
    ar = np.zeros(n + 200)
    for i in range(1, n + 200):
        ar[i] = 0.9 * ar[i - 1] + rng.normal(0, 1)
    ar = ar[200:] + 50.0
    Xa, ya, _ = make_supervised(ar, "level")
    pa = make_pipeline({**DEFAULT_PARAMS, "rf__n_estimators": 300, "rf__max_features": 1.0})
    with capture_warnings("selftest"):
        pa.fit(Xa, ya)
    imp = pd.Series(pa.named_steps["rf"].feature_importances_, index=FEATURE_NAMES)
    assert (imp >= 0).all() and abs(imp.sum() - 1) < 1e-6, "importances are not a distribution"
    print("(h2) importances are a valid distribution; on a stationary AR(1) the top three are "
          + ", ".join(f"{k} {100 * v:.0f}%" for k, v in imp.nlargest(3).items()))

    # (h3) pruning must zero exactly the named columns and nothing else.
    if len(FEATURE_NAMES) > 3:
        victim = FEATURE_NAMES[1]
        sel = TrendIndexSelector(use_capped=False, drop_idx=(1,))
        Z = sel.transform(np.ones((2, len(FEATURE_NAMES))))
        assert (Z[:, 1] == 0).all() and Z[:, 2].all(), "pruning zeroed the wrong column"
        print(f"(h3) feature pruning zeroes exactly the named column (tested on '{victim}')")

    # (i) the imputer must live INSIDE the pipeline, or its medians are fitted on held-out rows.
    assert isinstance(make_pipeline(), Pipeline) and "impute" in make_pipeline().named_steps, \
        "the imputer is not a pipeline step - its medians would be fitted on held-out rows"
    print("(i) median imputation is a pipeline step, so it is refitted per fold")

    # (j) the period -> month conversion must be exact on a KNOWN path.
    _s, _e = grain_edges(CAL_INDEX, GRAIN)
    flat = working_days_edges(_s, _e)
    want_all = working_days(MONTHLY_INDEX)
    for _k in (CONFIG["MIN_TRAIN_MONTHS"], len(MONTHLY_INDEX) - 1):
        mm = np.zeros(len(MONTHLY_INDEX), bool)
        mm[int(_k)] = True
        got, want = float(periods_to_months(flat, mm)[0]), float(want_all[int(_k)])
        assert abs(got - want) < 1e-6, (f"grain {GRAIN}: a flat one-per-working-day path "
                                        f"aggregates to {got:.3f}, not {want:.0f}")
    print(f"(j) period -> month conversion is exact at grain {GRAIN}")

    # (j2) THE FORWARD-BOUNDARY BUG: the first forecast month is straddled by a period that
    #      belongs to HISTORY, so the recursion never assigns it a value. If the conversion
    #      cannot survive that, every forward forecast at a finer grain is non-finite.
    m_fwd = np.zeros(len(ALL_MONTHS), dtype=bool)
    m_fwd[len(MONTHLY_INDEX)] = True
    want0 = float(ALL_MONTHS_WD[len(MONTHLY_INDEX)])
    assert abs(float(periods_to_months(flat, m_fwd)[0]) - want0) < 1e-6, \
        "the first forecast month does not reconstruct from a complete path"
    touch = np.where(ALLOC[:, len(MONTHLY_INDEX)] > 1e-9)[0]
    if touch.size > 1:
        holed = flat.copy()
        holed[touch[0]] = np.nan
        got = float(periods_to_months(holed, m_fwd)[0])
        assert np.isfinite(got) and abs(got - want0) < 1e-6, \
            (f"grain {GRAIN}: blanking the straddling period gave {got}, not {want0:.0f} - "
             f"the forward horizon would be non-finite")
        print(f"(j2) first forecast month {ALL_MONTHS[len(MONTHLY_INDEX)]:%Y-%m} is spanned by "
              f"{touch.size} periods; blanking the straddling one still reconstructs it")
    else:
        print(f"(j2) at grain {GRAIN} no period straddles the forecast boundary")

    # (k) THE CUSTOMER-SIGNAL leakage test. These columns are not functions of y, so (a)
    #     cannot catch a mistake in them. What makes them safe is the lag: at position t the
    #     model reads the value from t-GM, and a horizon of at most GM periods means that is
    #     always at or before the forecast origin.
    if USE_EXOG_FEATURES:
        Hp = months_to_periods(CONFIG["WF12_HORIZON"])
        assert Hp <= GM, (f"customer signals are lagged {GM} periods but the horizon is {Hp} - "
                          f"the last forecast step would read a value from after its origin")
        base = EXOG_COLS[0].rsplit("_lag", 1)[0]
        tt = int(min(len(CAL_INDEX) - 1, GM + 7))
        a_, b_ = CAL[EXOG_COLS[0]].to_numpy()[tt], GEXOG[base].to_numpy()[tt - GM]
        assert (np.isnan(a_) and np.isnan(b_)) or np.isclose(a_, b_), \
            f"{EXOG_COLS[0]} is not {base} shifted by {GM} periods"
        assert not np.isfinite(CAL[EXOG_COLS[0]].to_numpy()[:GM]).any(), \
            "the customer-signal lag is populated before one full cycle has elapsed"
        print(f"(k) customer signals {EXOG_COLS} are {base}-style series shifted by exactly "
              f"{GM} periods, and the horizon is {Hp} <= {GM} periods, so every value read is "
              f"already known at the origin")
    else:
        print("(k) customer-signal block is off - nothing to check")


_grain_before = GRAIN
for _g in AGG_CANDIDATES:
    print(f"\n--- self-tests at grain '{_g}' ({GRAIN_SETTINGS[_g]['label']}) "
          + "-" * (46 - len(GRAIN_SETTINGS[_g]['label'])))
    selftest(_g)
set_grain(_grain_before)

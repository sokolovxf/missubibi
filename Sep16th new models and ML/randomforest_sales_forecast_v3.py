def build_feature_frame(verbose=True):
    """(Re)build the calendar frame and feature list for the ACTIVE grain and feature set. A
    function because the Section 8 trials toggle whole blocks and must rebuild from the SAME
    code rather than a drifting copy of it."""
    global CAL, CAL_COLS, CAL_ARR, DYN_COLS, FEATURE_NAMES, MAX_LAG
    global USE_WD_FEATURES, USE_EXOG_FEATURES, TREND_COL_IDX, EXOG_COLS

    _cal, n_cal = {}, len(CAL_INDEX)
    if CONFIG["RF_TREND_INDEX"]:
        _cal["t_index"] = np.arange(n_cal, dtype=float)
    if CONFIG["RF_MONTH_NUMBER"]:
        _cal["month_num"] = CAL_INDEX.month.to_numpy(dtype=float)
    for _k in range(1, int(CONFIG["RF_FOURIER_K"]) + 1):
        _tt = np.arange(n_cal, dtype=float)
        _cal[f"sin{_k}"] = np.sin(2 * np.pi * _k * _tt / GM)
        _cal[f"cos{_k}"] = np.cos(2 * np.pi * _k * _tt / GM)
    USE_WD_FEATURES = bool(CONFIG["USE_WORKING_DAYS"])
    if USE_WD_FEATURES:
        _cal["working_days"] = (GCAL_WD - float(GWD.mean())) / (float(GWD.std()) or 1.0)
        _lost = GCAL_WD_NOHOL - GCAL_WD
        if float(np.ptp(_lost)) > 0:     # constant when HOLIDAY_COUNTRY is NONE
            _cal["holidays_lost"] = _lost.astype(float)
    # Customer signals enter at a FULL SEASONAL-CYCLE lag: at position t the model reads the
    # value from t-GM, which is at or before the origin for every step of a GM-period horizon
    # (asserted in self-test (k)). Nothing here is ever read at a position it could not know.
    USE_EXOG_FEATURES = bool(CONFIG["USE_EXOG_SIGNALS"])

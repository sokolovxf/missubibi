def oos_residual_pool(series_name, model_name, frame=None):
    """Out-of-sample errors by horizon: err = actual - pred, so pred + quantile(err) is a band
    built from errors this configuration actually made on unseen data. WF12 gives one error
    per fold per horizon, too thin for a 5th/95th percentile, so WF1 errors scaled by sqrt(h)
    are pooled in below MIN_PI_POOL - an approximation, labelled wherever the band is drawn.
    """
    frame = resid_df if frame is None else frame
    d = frame[(frame["series"] == series_name) & (frame["model"] == model_name)]
    d12, d1 = d[d["scheme"] == "WF12"], d[d["scheme"] == "WF1"]
    base = d1["err"].to_numpy(dtype=float)
    base = base[np.isfinite(base)]
    pool = {}
    for h in range(1, HORIZON + 1):
        e = d12[d12["h"] == h]["err"].to_numpy(dtype=float)
        e = e[np.isfinite(e)]
        if e.size < MIN_PI_POOL and base.size >= 3:
            e = np.concatenate([e, base * np.sqrt(h)])
        pool[h] = e if e.size else np.array([0.0])
    return pool


def oos_interval(point, pool, alpha=0.10):
    """90% band = point + the empirical 5th/95th percentile of out-of-sample error at that h."""
    point = np.asarray(point, dtype=float)
    lo, hi = np.empty(point.size), np.empty(point.size)
    for i in range(point.size):
        e = np.asarray(pool.get(i + 1, np.array([0.0])), dtype=float)
        e = e[np.isfinite(e)]
        if e.size == 0:
            e = np.array([0.0])
        q_lo, q_hi = np.percentile(e, [100 * alpha / 2, 100 * (1 - alpha / 2)])
        lo[i], hi[i] = point[i] + q_lo, point[i] + q_hi
    return lo, hi



"""## 6. Metrics and fold definitions

- **Pooled metrics are the headline** (all residuals at once); per-fold mean/sd is kept as a
  stability measure only — averaging per-fold ratios when a `WF1` fold has one observation is
  a mean of ratios and is badly skewed.
- **One fixed MASE scale per series**, from the initial training window, so every fold is on
  the same scale and can be pooled.
- **Bias (ME, MPE) is measured**: a systematically high or low model compounds over a plan year.
- **MAPE is demoted** — unusable at zero, unstable near it. MASE, then sMAPE, then MAE/RMSE.
"""

def naive_scale_fixed(s, n_ref, usable=None):
    """MASE denominator: MAE of the lag-1 naive forecast over the initial USABLE window."""
    v = s.to_numpy(dtype=float)
    if usable is not None:
        v = v[np.asarray(usable, bool)]
    d = np.abs(np.diff(v[:int(n_ref)]))
    d = d[np.isfinite(d)]
    return float(np.mean(d)) if d.size and np.mean(d) != 0 else np.nan


MASE_SCALE = {n: naive_scale_fixed(s, CONFIG["MIN_TRAIN_MONTHS"], USABLE)
              for n, s in series_dict.items()}
print(f"fixed MASE scale (lag-1 naive MAE over the first {CONFIG['MIN_TRAIN_MONTHS']} usable "
      f"months):\n" + "\n".join(f"  {k:<16} {v:,.2f}" for k, v in MASE_SCALE.items()))


def core_metrics(y_true, y_pred, scale):
    yt, yp = np.asarray(y_true, float), np.asarray(y_pred, float)
    ok = np.isfinite(yt) & np.isfinite(yp)
    out = {k: np.nan for k in ("MASE", "sMAPE_%", "MAE", "RMSE", "ME", "MPE_%", "MAPE_%")}
    out.update({"n": 0, "n_pred_missing": int((~ok).sum()), "n_zero_actual": 0,
                "n_neg_actual": 0})
    yt, yp = yt[ok], yp[ok]
    if yt.size == 0:
        return out
    err = yt - yp
    out.update({"MAE": float(np.mean(np.abs(err))), "RMSE": float(np.sqrt(np.mean(err ** 2))),
                "ME": float(np.mean(err)),           # >0 => the model UNDER-forecasts
                "n": int(yt.size), "n_zero_actual": int((yt == 0).sum()),
                "n_neg_actual": int((yt < 0).sum())})
    nz = yt != 0
    if nz.any():
        out["MAPE_%"] = float(np.mean(np.abs(err[nz] / yt[nz])) * 100)
        out["MPE_%"] = float(np.mean(err[nz] / yt[nz]) * 100)
    den = np.abs(yt) + np.abs(yp)
    if (den > 0).any():
        out["sMAPE_%"] = float(np.mean(2 * np.abs(err[den > 0]) / den[den > 0]) * 100)
    if scale is not None and np.isfinite(scale) and scale > 0:
        out["MASE"] = out["MAE"] / scale
    return out


def make_folds(index, fys, cfg, usable=None):
    """WF1 (rolling one-step) and WF12 (multi-origin 12-step), over USABLE months only.

    A fold trains on the usable months strictly before its origin and is scored on the usable
    months of its horizon, and an origin exists only once MIN_TRAIN_MONTHS usable months
    precede it - so masking a fiscal year shortens the record instead of corrupting it.
    """
    n = len(index)
    u = np.ones(n, bool) if usable is None else np.asarray(usable, bool)
    n_before = np.concatenate([[0], np.cumsum(u)[:-1]])   # usable months strictly before i
    mt, H = int(cfg["MIN_TRAIN_MONTHS"]), int(cfg["WF12_HORIZON"])
    folds, skipped = [], 0
    for origin in range(n):                                                  # WF1
        if not u[origin] or n_before[origin] < mt:
            continue
        tr = np.zeros(n, bool)
        tr[:origin] = True
        tr &= u
        te = np.zeros(n, bool)
        te[origin] = True
        folds.append({"scheme": "WF1", "fold": str(index[origin].date())[:7],
                      "train_mask": tr, "test_mask": te, "origin": origin})
    origins = [o for o in range(n) if n_before[o] >= mt]
    if origins:
        o = origins[0]
        while o + H <= n:
            tr = np.zeros(n, bool)
            tr[:o] = True
            tr &= u
            te = np.zeros(n, bool)
            te[o:o + H] = True
            te &= u
            if int(te.sum()) >= 3 and int(tr.sum()) >= mt:
                folds.append({"scheme": "WF12", "fold": f"from {str(index[o].date())[:7]}",
                              "train_mask": tr, "test_mask": te, "origin": o})
            else:
                skipped += 1
            o += int(cfg["WF12_STEP"])
    if cfg["RUN_LOFO"]:                                                      # advisory only
        lab = np.array([fy_of(t) for t in index])
        for fy in fys:
            te = (lab == fy) & u
            if te.any():
                folds.append({"scheme": "LOFO", "fold": f"FY{fy}", "train_mask": (~te) & u,
                              "test_mask": te, "origin": None})
    if skipped:
        print(f"  {skipped} WF12 origin(s) skipped: too few usable test months after masking")
    return folds



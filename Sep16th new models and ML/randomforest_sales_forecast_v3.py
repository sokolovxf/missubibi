def tune_rf(y_masked, mode, context=""):
    """Hyperparameters by a TIME-ORDERED search (an ordinary KFold would score a candidate on
    months preceding its own training rows). Scores ONE-STEP-AHEAD MAE — the cheap
    criterion — so it settles nothing structural; the transform and the bias correction
    come afterwards from rf_cv_rolling_stats at CV_HORIZON steps."""
    X, yv, pos = make_supervised(y_masked, mode)
    n_rows = X.shape[0]
    n_splits = int(min(CONFIG["RF_TUNE_SPLITS"], max(2, n_rows - 2)))
    if n_rows < n_splits + 2:
        return dict(DEFAULT_PARAMS), np.nan
    grid = dict(CONFIG["RF_PARAM_GRID"])
    try:
        with capture_warnings(f"tune[{context}]"):
            cv = TimeSeriesSplit(n_splits=n_splits)
            jobs = int(CONFIG.get("RF_SEARCH_JOBS", 1))
            if str(CONFIG["RF_SEARCH"]).lower() == "grid":
                search = GridSearchCV(make_pipeline(), grid, cv=cv, n_jobs=jobs,
                                      scoring="neg_mean_absolute_error")
            else:
                n_comb = int(np.prod([len(v) for v in grid.values()]))
                search = RandomizedSearchCV(
                    make_pipeline(), grid, cv=cv, n_jobs=jobs,
                    scoring="neg_mean_absolute_error",
                    n_iter=int(min(CONFIG["RF_N_ITER"], n_comb)),
                    random_state=CONFIG["SEED"])
            # Recency weights go into the CV too, so candidates are scored under the same
            # weighting the final fit uses. Older sklearn builds that cannot slice fit params
            # per split fall back to the unweighted search rather than mis-aligning them.
            w = recency_weights(pos)
            if w is None:
                search.fit(X, yv)
            else:
                try:
                    search.fit(X, yv, rf__sample_weight=w)
                except Exception as e:
                    log_failure(f"tune-weighted[{context}]", e)
                    search.fit(X, yv)
        return dict(search.best_params_), float(-search.best_score_)
    except Exception as e:
        log_failure(f"tune[{context}]", e)
        return dict(DEFAULT_PARAMS), np.nan


TUNE_STABILITY_ROWS = []


def tuning_stability(y_masked, mode, context="", windows=None):
    """Refit the SAME search on two overlapping trailing windows and report agreement. Feeds
    back into nothing - it asks whether the config is a property of the series or of which
    36-vs-42 months it happened to see."""
    if not CONFIG.get("RF_STABILITY_CHECK", False):
        return None
    windows = tuple(CONFIG.get("RF_STABILITY_WINDOWS", (36, 42))) if windows is None else windows
    y_masked = np.asarray(y_masked, dtype=float)
    keys = ("rf__n_estimators", "rf__max_depth", "rf__min_samples_leaf")
    out, picks = {"series": context, "mode": mode}, {}
    for w in (int(x) for x in windows):
        if len(y_masked) < w:
            picks[w] = None
            continue
        params, _ = tune_rf(y_masked[-w:], mode, f"{context}|stab{w}")
        picks[w] = tuple(params.get(k) for k in keys)
        out[f"win{w}"] = "n={}, depth={}, leaf={}".format(*picks[w])
    got = [v for v in picks.values() if v is not None]
    out["agree"] = (len(got) == len(windows) and len(set(got)) == 1) if got else np.nan
    with _LOG_LOCK:
        TUNE_STABILITY_ROWS.append(out)
    return out


# ---- 7.3  Rolling-origin held-out CV inside the training window ----------------------------------
def rf_cv_rolling_stats(y_masked, spec, context=""):
    """Rolling-origin, multi-horizon MAE inside the TRAINING window only, scored RECURSIVELY so a
    transform that unravels on its own predictions is caught here, not in production. Inner
    windows are floored at CV_MIN_TRAIN_MONTHS, not MIN_TRAIN_MONTHS - tying them together
    would switch this off exactly where history is thinnest. Returns (MAE, mean signed error,
    its standard error); err = actual - pred.
    """
    H = months_to_periods(CONFIG["CV_HORIZON"])
    n_origins = int(CONFIG["CV_ORIGINS"])
    y_masked = np.asarray(y_masked, dtype=float)
    obs_idx = np.where(np.isfinite(y_masked))[0]
    cv_min = months_to_periods(CONFIG.get("CV_MIN_TRAIN_MONTHS", CONFIG["MIN_TRAIN_MONTHS"]))
    if obs_idx.size < cv_min + 2:
        return np.nan, np.nan, np.nan
    H = int(min(H, max(1, obs_idx.size - cv_min)))
    errs, per_origin = [], []
    for j in range(n_origins):
        k = H + j
        if k > obs_idx.size or obs_idx.size - k < cv_min:
            break
        cut = int(obs_idx[-k])
        y = y_masked.copy()
        y[cut:] = np.nan                    # hide the origin period and everything after it
        try:
            X, yv, tpos = make_supervised(y, spec["mode"])
            if X.shape[0] < 3:
                continue
            pipe = make_pipeline(spec["params"])
            with capture_warnings(f"cv[{context}]"):
                fit_pipe(pipe, X, yv, tpos)
            pos = [int(p) for p in obs_idx[obs_idx >= cut][:H]]
            path = rf_forecast_positions(pipe, y, pos, spec["mode"])
            cur = [float(y_masked[p]) - float(path[p]) for p in pos if np.isfinite(path[p])]
            if cur:
                per_origin.append(np.asarray(cur, dtype=float))
                errs.extend(cur)
        except Exception as e:
            log_failure(f"cv[{context}]", e)
    if not errs:
        return np.nan, np.nan, np.nan
    mae = float(np.mean(np.abs(np.asarray(errs, dtype=float))))
    # The bias is a RECENCY-WEIGHTED mean over origins: j=0 hides the fewest periods, so it is
    # closest to the forecast date. A flat average is a global correction and tracks nothing.
    lam = float(CONFIG.get("BIAS_RECENCY_LAMBDA", 1.0))
    means = np.array([o.mean() for o in per_origin], dtype=float)
    w = np.array([lam ** j for j in range(means.size)], dtype=float)
    bias = float(np.sum(w * means) / float(w.sum()))
    if means.size > 1:
        var = float(np.sum(w * (means - bias) ** 2) / float(w.sum()))
        se = float(np.sqrt(var / (means.size - 1)))
    else:
        # ONE origin cannot give a standard error ACROSS origins, and the within-origin one is
        # a different quantity: six months on the wrong side of a level shift have a tiny
        # spread, which would read as a near-certain tilt. Unbounded; the caller then declines.
        se = np.inf
    return mae, bias, se



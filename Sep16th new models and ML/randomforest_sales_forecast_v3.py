# ---- 8.0  How many workers, measured rather than assumed -----------------------------------
# Parallelism across series is a thread pool, so whether it helps is a question about the
# GIL, and the answer is not obvious: a RandomForest fit releases the GIL inside the Cython
# tree builder, but on ~25x25 matrices the Python-level per-tree bookkeeping around it
# dominates, and then threads only contend. This measures the actual workload - a fit plus
# the one-row recursion the folds spend most of their time in - and takes whichever is
# faster. It costs a few seconds and it has been wrong in both directions on different
# machines, which is exactly why it is measured here instead of hardcoded.
WORKER_CACHE = {}


def calibrate_workers(n_rows=None, target=None, reps=3):
    rng = np.random.default_rng(0)
    Xc = rng.normal(size=(int(n_rows or 24), max(8, len(FEATURE_NAMES))))
    yc = Xc[:, 0] * 2 + rng.normal(size=Xc.shape[0]) * 0.3

    def unit(_):
        for i in range(reps):
            pipe = make_pipeline({**DEFAULT_PARAMS, "rf__n_estimators": 200})
            pipe.fit(Xc, yc)
            pr = _row_predictor(pipe)
            for _ in range(8):
                pr(Xc[:1])
        return 1

    n = int(target or min(len(series_dict), os.cpu_count() or 1))
    t0 = time.time()
    [unit(i) for i in range(n)]
    serial = time.time() - t0
    t0 = time.time()
    Parallel(n_jobs=n, prefer="threads")(delayed(unit)(i) for i in range(n))
    threaded = time.time() - t0
    speedup = serial / max(threaded, 1e-9)
    pick = n if speedup > 1.15 else 1
    print(f"    worker calibration @{Xc.shape[0]} rows: {n} units took {serial:.1f}s "
          f"serially vs {threaded:.1f}s on {n} threads ({speedup:.2f}x) -> {pick} worker(s)"
          + ("" if pick > 1 else "  [the GIL wins at this matrix size]"), flush=True)
    return pick


def workers_for(grain):
    """How many workers to use at this grain. Calibrated once per grain, because the
    answer genuinely differs: a weekly training matrix is ~8x taller than a monthly one,
    and the Cython tree builder's nogil section is a bigger share of the work there."""
    forced = CONFIG["N_JOBS_SERIES"]
    if str(forced).lower() != "auto":
        return int(max(1, min(int(forced), len(series_dict))))
    if grain not in WORKER_CACHE:
        WORKER_CACHE[grain] = calibrate_workers(
            n_rows=max(8, int(len(GRAIN_DATA[grain]["index"]) * 0.6)))
    return WORKER_CACHE[grain]


def pooled_mase(pred_map, scheme, model="RandomForest"):
    """Pooled MASE per series over every fold — always against MONTHLY actuals and the fixed
    MASE_SCALE, whatever grain produced them. The only reason two grains are comparable."""
    out = {}
    for sn in series_dict:
        a, p = [], []
        for (s2, m2, sc, fd), v in pred_map.items():
            if s2 == sn and m2 == model and sc == scheme:
                a.append(series_dict[sn].loc[v.index].to_numpy(dtype=float))
                p.append(v.to_numpy(dtype=float))
        if a:
            out[sn] = core_metrics(np.concatenate(a), np.concatenate(p), MASE_SCALE[sn])["MASE"]
    return out


def _run_series(series_name, folds, grain, tag):
    """Every fold of one series at the active grain, in its own thread: per-fit state is
    thread-local and the forest is n_jobs=1, so nothing here races."""
    rows, preds, specs = [], {}, []
    s = series_dict[series_name]
    scale = MASE_SCALE[series_name]
    with _apply_prune(series_name):
        for f in folds:
            tr, te = f["train_mask"], f["test_mask"]
            ctx = f"{series_name}|{f['scheme']}|{f['fold']}|{tag}"
            t0 = time.time()
            spec, ref = ((None, None) if f["scheme"] == "LOFO"
                         else wf_spec_for(series_name, f["origin"]))
            pred, used, status = rf_fold(s, tr, te, series_name, spec=spec, context=ctx)
            secs = time.time() - t0
            preds[(series_name, "RandomForest", f["scheme"], f["fold"])] = \
                pd.Series(pred, index=s.index[te], name="RandomForest")
            rows.append({"series": series_name, "model": "RandomForest", "scheme": f["scheme"],
                         "fold": f["fold"], "origin": f["origin"], "status": status,
                         "grain": grain, "train_months": int(tr.sum()),
                         "n_train_rows": int(np.isfinite(
                             grain_masked_values(series_name, tr)).sum()),
                         **core_metrics(s[te].to_numpy(), pred, scale)})
            with _LOG_LOCK:
                FOLD_TIMING.append({"series": series_name, "scheme": f["scheme"],
                                    "tag": tag, "secs": secs})
            _p, _r = (used.get("params", {}) or {}), (used.get("rules", {}) or {})
            specs.append({"series": series_name, "grain": grain, "featset": featset_tag(),
                          "scheme": f["scheme"], "fold": f["fold"],
                          "spec": spec_label(used), "mode": used.get("mode"),
                          "mode_raw": used.get("mode_raw"),
                          "use_capped": _p.get("sel__use_capped"),
                          "n_estimators": _p.get("rf__n_estimators"),
                          "max_depth": _p.get("rf__max_depth"),
                          "min_samples_leaf": _p.get("rf__min_samples_leaf"),
                          "max_features": _p.get("rf__max_features"),
                          "rule_profile": _r.get("name"), "recency": _r.get("recency"),
                          "force": _r.get("force"), "regime": _r.get("regime"),
                          "tune_mae": used.get("tune_mae"), "cv_mae": used.get("cv_mae"),
                          "cv_bias": used.get("cv_bias"), "bias_adj": used.get("bias_adj"),
                          "bias_shrink": used.get("bias_shrink"),
                          "screen_failed": used.get("screen_failed"),
                          "screen": used.get("screen"),
                          "n_implausible": used.get("n_implausible"),
                          "seasonal_strength_train": used.get("seasonal_strength_train"),
                          "selected_on_months": ref})
    return rows, preds, specs


def run_pass(grain, tag, series_names=None, folds=None):
    """One full walk-forward pass at one grain, parallel across SERIES.

    Threads, not processes: the calendar frame is a module global a thread shares rather than
    pickles, everything per-fit lives in the thread-local VIEW, and sklearn releases the GIL
    inside tree building, so this is real parallelism. The forest stays n_jobs=1."""
    set_grain(grain)
    folds = WF_FOLDS if folds is None else folds
    names = list(series_dict) if series_names is None else list(series_names)
    n_jobs = int(max(1, min(workers_for(grain), len(names))))
    t0 = time.time()          # after calibration, so a one-off probe is not billed here
    out = Parallel(n_jobs=n_jobs, prefer="threads")(
        delayed(_run_series)(sn, folds, grain, tag) for sn in names)
    rows, preds, specs = [], {}, []
    for r, p, s in out:
        rows += r
        preds.update(p)
        specs += s
    cache_flush()
    _w = time.time() - t0
    _cpu = sum(r["secs"] for r in FOLD_TIMING if r["tag"] == tag)
    print(f"    {len(names)} series x {len(folds)} folds at grain '{grain}' "
          f"[{featset_tag()}] in {_w:.0f}s wall / {_cpu:.0f}s of fold work "
          f"({n_jobs} threads => {_cpu / max(_w, 1e-9):.1f}x)", flush=True)
    return rows, preds, specs


def wf1_veto(cand12, base12, cand1, base1, margin, tol=None):
    """Accept a WF12-chosen challenger only if WF1 does not contradict it. WF1 never votes, it
    only vetoes: a change that improves 12-month pooled MASE while making one-step MASE worse
    is far more likely selection across a handful of origins than skill, and WF1 has ~24
    origins to say so with. The one guard against selecting on the metric we then report."""
    tol = float(CONFIG["WF1_VETO_TOL"]) if tol is None else float(tol)
    if not (np.isfinite(cand12) and np.isfinite(base12)):
        return False, "no WF12 evidence"
    if base12 - cand12 < margin:
        return False, f"WF12 gain {base12 - cand12:+.3f} below the {margin:.3f} margin"
    if np.isfinite(cand1) and np.isfinite(base1) and cand1 > base1 + tol:
        return False, (f"VETOED by WF1: WF12 {base12:.3f}->{cand12:.3f} but WF1 "
                       f"{base1:.3f}->{cand1:.3f} (worse by {cand1 - base1:+.3f} > "
                       f"{tol:.3f} tolerance)")
    return True, f"WF12 {base12:.3f}->{cand12:.3f}, WF1 {base1:.3f}->{cand1:.3f}"



"""## 8. Run the walk-forward evaluation

Six passes, in order; nothing is chosen until the pass before it has a number.

| pass | question | decided on |
|---|---|---|
| 8.1 grain sweep | monthly / fortnightly / weekly, identical folds | — |
| 8.2 grain per series | which grain each series earned | WF12, **WF1 veto** |
| 8.3 working days | do those two columns earn their place? | WF12 mean, **WF1 veto** |
| 8.4 customer signals | do active-customer / order / new-mix counts help? | WF12 mean, **WF1 veto** |
| 8.5 feature pruning | drop columns the trees never split on | WF12 per series, **WF1 veto** |
| 8.6 assembly | the folds of the configuration actually being shipped | — |

Everything in 8.2–8.5 is chosen on the metric Section 10 reports, so the WF1 column is the
clean read on whether the choice generalised — and a challenger that wins WF12 while losing
WF1 is rejected in code.

The three feature trials hold the hyperparameters and the rule profile **fixed** at what
8.1 froze, so each trial changes exactly one thing and is a real A/B rather than two
changes at once. `SeasonalNaive` is fitted once at the end: grain-independent, free, and
the reference the MASE scale is read against.
"""


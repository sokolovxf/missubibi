def feature_trial(name, flag, series_names=None):
    """Turn one feature block OFF, re-run the same folds, keep the better mean WF12 MASE —
    subject to the WF1 veto. Measured, not inferred from importance: low importance says the
    trees rarely split on a column, not that those splits are costing accuracy."""

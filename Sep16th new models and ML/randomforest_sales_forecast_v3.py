    GIDX = pd.DatetimeIndex(d["index"])
    GSER, GWD = d["series"], np.asarray(d["wd"], dtype=float)
    CAL_INDEX = pd.DatetimeIndex(d["cal_index"], name="period")
    GCAL_WD = np.asarray(d["cal_wd"], dtype=float)
    GCAL_WD_NOHOL = np.asarray(d["cal_wd_nohol"], dtype=float)
    GEXOG = d["exog"]
    N_PERIODS = len(GIDX)
    LAGS = tuple(int(x) for x in d["lags"])
    DIFF_LAGS = tuple(int(x) for x in d["diff_lags"])
    ROLLS = tuple(int(x) for x in d["rolls"])
    YOY_K = int(max(1, round(GM / 4.0)))      # a quarter cycle: 3 months, 6 fortnights, 13 weeks
    CAP_PERIODS = int(d["cap"])
    # 0.97 monthly means "a row a year old is worth 0.69 of a fresh one" — re-expressed per

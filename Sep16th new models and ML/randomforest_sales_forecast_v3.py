GRAIN_DATA = {}


def build_grain(grain, verbose=True):
    """Everything the engine needs for one grain, built once."""
    idx = grain_index(grain)
    sd = {"revenue_total": grain_series(model_df, "revenue", idx, grain),
          "qty_total": grain_series(model_df, "quantity", idx, grain)}
    for cat in top_categories:
        sd[f"revenue_{cat}"] = grain_series(model_df, "revenue", idx, grain, category=cat)
    sd["revenue_other"] = grain_series(model_df, "revenue", idx, grain, exclude=top_categories)
    g = GRAIN_SETTINGS[grain]
    horizon = int(CONFIG["WF12_HORIZON"])
    fwd = int(np.ceil(horizon * g["period"] / 12.0)) + 2     # + slack so the last month is spanned
    cal_idx = grain_index(grain, upto=WINDOW_END + pd.DateOffset(months=horizon + 3))
    cal_idx = cal_idx[:len(idx) + fwd]
    c_starts, c_ends = grain_edges(cal_idx, grain)
    GRAIN_DATA[grain] = {
        "grain": grain, "index": idx, "cal_index": cal_idx, "series": sd,
        "period": g["period"], "fwd": fwd,
        "wd": working_days_edges(*grain_edges(idx, grain)),
        "cal_wd": working_days_edges(c_starts, c_ends),
        "cal_wd_nohol": working_days_edges(c_starts, c_ends, country="NONE"),
        "alloc": month_allocation(idx, grain, MONTHLY_INDEX),
        "exog": grain_exog(cal_idx, grain),
        **{k: g[k] for k in ("lags", "diff_lags", "rolls", "cap", "label")}}
    if verbose:
        print(f"  {grain:<3} ({g['label']:<11}) {len(idx):>4} periods, cycle {g['period']}, "
              f"+{fwd} forward periods for the {horizon}-month horizon")
    return GRAIN_DATA[grain]



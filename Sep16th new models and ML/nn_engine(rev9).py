# FIX 3: prev_month_qty_2/3 NaNs used to be filled with prev_month_qty_1, fabricating a
# repeated observation the item never had. Filled with 0 instead - a neutral "no history at
# this depth" marker, applied consistently to every lagged column and identical in train and
# test, so nothing is carried across the split.
LAG_COLS = ([f'prev_month_qty_{i}' for i in (1, 2, 3)]
            + [f'prev_{c}_1' for c in LAGGED_EXTRAS] + [f'prev_{c}_2' for c in LAGGED_EXTRAS]
            + ['hist_mean_qty', 'hist_max_qty', 'hist_n_months',
               'roll3_mean_qty', 'roll6_mean_qty'])

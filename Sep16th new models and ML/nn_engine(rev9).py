"""## 6. Neural Network Architecture

Builds the mixed-input binary classifier using a dense numeric pathway and learned embeddings for categorical features.
"""

# 5. Model Architecture (Binary Output)
def build_binary_model(n_numeric, cat_vocabs, units1=256, units2=256, units3=128,
                       drop1=0.2, drop2=0.25, drop3=0.2):
    num_input = layers.Input(shape=(n_numeric,), name='numeric_input')
    num_x = layers.Dense(units1, activation='relu')(num_input)
    num_x = layers.BatchNormalization()(num_x)
    num_x = layers.Dropout(drop1)(num_x)

    cat_inputs, cat_embeds = [], []
    for name, vocab in cat_vocabs.items():
        # FIX 6: StringLookup with num_oov_indices=1 emits indices 0..len(vocab), i.e.
        # len(vocab)+1 distinct values in total. vocab_size already counts that OOV slot, so
        # input_dim=vocab_size is exactly right; the old vocab_size+1 reserved a second,
        # permanently unused embedding row.
        vocab_size = len(vocab) + 1
        inp = layers.Input(shape=(1,), dtype=tf.string, name=f'{name}_input')
        lookup = layers.StringLookup(vocabulary=vocab, num_oov_indices=1)(inp)
        emb = layers.Embedding(input_dim=vocab_size, output_dim=16)(lookup)
        cat_inputs.append(inp)
        cat_embeds.append(layers.Flatten()(emb))

    combined = layers.Concatenate()([num_x] + cat_embeds)
    x = layers.Dense(units2, activation='relu')(combined)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(drop2)(x)
    x = layers.Dense(units3, activation='relu')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(drop3)(x)

    return [num_input] + cat_inputs, x


def make_model(lr=1e-3, weight_decay=1e-4, seed=SEED, **kw):
    """A freshly-seeded, compiled model. Seeding inside the factory is what makes a repeat
    run bit-identical rather than merely similar."""
    reset_seeds(seed)
    inputs, trunk = build_binary_model(X_train_num.shape[1], cat_vocabs, **kw)
    out = layers.Dense(1, activation='sigmoid', name='demand_binary')(trunk)
    m = Model(inputs=inputs, outputs=out)
    m.compile(optimizer=AdamW(learning_rate=lr, weight_decay=weight_decay),
              loss='binary_crossentropy', metrics=['accuracy'])
    return m


train_inputs = [X_train_num] + [X_train_cat[c] for c in feature_cols_cat]
test_inputs  = [X_test_num]  + [X_test_cat[c]  for c in feature_cols_cat]

# The LAST 15% of the (chronologically ordered) training rows is the validation split Keras
# uses for early stopping. The same slice - never the test set - is what tunes the decision
# threshold in Section 8.
VAL_FRAC = 0.15
n_val = int(len(y_train_clf) * VAL_FRAC)
val_slice = slice(len(y_train_clf) - n_val, len(y_train_clf))
val_inputs = [a[val_slice] for a in train_inputs]
y_val_clf = y_train_clf[val_slice]
print(f'train rows {len(y_train_clf):,} | of which validation (chronological tail) {n_val:,}')

"""## 7. Model Training

Trains with balanced class weights and early stopping. Training output is intentionally quiet so the notebook stays readable.
"""

def train_once(lr=1e-3, epochs=150, batch_size=128, patience=15, seed=SEED, **kw):
    """Build + fit one model. Everything that varies between runs is reset inside."""
    model = make_model(lr=lr, seed=seed, **kw)
    hist = model.fit(
        x=train_inputs, y=y_train_clf,
        validation_split=VAL_FRAC,
        epochs=epochs, batch_size=batch_size,
        class_weight=class_weight_dict,
        callbacks=[EarlyStopping(monitor='val_loss', mode='min', patience=patience,
                                 restore_best_weights=True)],
        verbose=0,
    )
    return model, hist


# --- light hyperparameter search, scored on the VALIDATION tail only ---------------------
# The test set is never consulted here; it is touched once, in Section 8, after the
# configuration and the threshold are both frozen.
CANDIDATES = [
    dict(tag='base  lr1e-3 256/256/128 do.20/.25/.20', lr=1e-3),
    dict(tag='lower lr5e-4 256/256/128 do.20/.25/.20', lr=5e-4),
    dict(tag='wider lr1e-3 512/256/128 do.30/.30/.20', lr=1e-3, units1=512, drop1=0.3, drop2=0.3),
]
search_rows = []
for cfg in CANDIDATES:
    tag = cfg.pop('tag')
    m, _ = train_once(**cfg)
    p = m.predict(val_inputs, verbose=0).flatten()
    search_rows.append({'config': tag, 'val_acc': accuracy_score(y_val_clf, (p > 0.5).astype(int)),
                        'val_auc': roc_auc_score(y_val_clf, p), **cfg})
search_df = pd.DataFrame(search_rows)
print(search_df[['config', 'val_acc', 'val_auc']].to_string(index=False,
                                                            float_format=lambda v: f'{v:.4f}'))

best = search_df.sort_values('val_auc', ascending=False).iloc[0]
BEST_CFG = {k: best[k] for k in ('lr', 'units1', 'drop1', 'drop2') if k in search_df.columns
            and pd.notna(best[k])}
print(f'\nselected on VALIDATION AUC: {best["config"]}')

clf_model, history_clf = train_once(**BEST_CFG)

"""## 8. Hold-Out Evaluation - ensemble, forced choice, and selective prediction

"""

# 6. Evaluation
# rev9 adds two things, BOTH tuned on the validation tail and never on the test set:
#   (A) a gradient-boosting model ensembled with the network, and
#   (B) selective prediction - the model is allowed to answer "Borderline" instead of
#       guessing on rows it cannot separate.
# Evidence that motivated (B): the target is a hard cut at >8 units on a small-integer
# quantity. Rows whose true quantity is 8 or 9 were ~46% wrong under rev8 - a coin flip by
# construction, not a modelling failure. Four unrelated algorithms all land at 84.7-85.5%
# forced-choice accuracy, which is the signature of a data ceiling rather than a model one.

# ---- (A) second opinion: gradient boosting on the SAME leak-free features -------------
gbm_num = feature_cols_num
Xtr_g = train_df[gbm_num].copy()
Xte_g = test_df[gbm_num].copy()
for c in feature_cols_cat:                       # shared category set, train-defined
    Xtr_g[c] = pd.Categorical(train_df[c], categories=cat_vocabs[c])
    Xte_g[c] = pd.Categorical(test_df[c], categories=cat_vocabs[c])

gbm = HistGradientBoostingClassifier(
    max_iter=400, learning_rate=0.06, early_stopping=True, validation_fraction=VAL_FRAC,
    class_weight='balanced', categorical_features='from_dtype', random_state=SEED)

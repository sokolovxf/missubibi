# FIX 2: avg_base_price / num_orders / num_customers were computed and never used. They are
# added as model inputs here at a ONE-MONTH LAG. Their same-month values are contemporaneous
# with the target (total_quantity for that same item-month) and would not be known at
# prediction time - using them unlagged inflates hold-out accuracy without the model
# forecasting anything. The lagged form carries the same signal honestly.
LAGGED_EXTRAS = ['avg_base_price', 'num_orders', 'num_customers']
for col in LAGGED_EXTRAS:
    agg[f'prev_{col}_1'] = grp[col].shift(1)

# rev8 FEATURE BLOCK - the item's own track record.
# Every one of these is built from .shift(1) first, so the current month never contributes to
# its own feature. An expanding window over the chronologically-sorted rows is exactly what
# would be available in production at prediction time: when forecasting month T you know
# everything up to T-1, including recent months that happen to fall in the test period.
_key = agg['item_internal_id']
_sh = agg.groupby(_key)['total_quantity'].shift(1)
_g = _sh.groupby(_key)
agg['hist_mean_qty'] = _g.expanding().mean().reset_index(level=0, drop=True)
agg['hist_max_qty'] = _g.expanding().max().reset_index(level=0, drop=True)
agg['hist_n_months'] = _g.expanding().count().reset_index(level=0, drop=True)
agg['roll3_mean_qty'] = _g.rolling(3, min_periods=1).mean().reset_index(level=0, drop=True)
agg['roll6_mean_qty'] = _g.rolling(6, min_periods=1).mean().reset_index(level=0, drop=True)

# second lag of the order/customer/price block (the first lag was added in rev7)
for col in LAGGED_EXTRAS:
    agg[f'prev_{col}_2'] = grp[col].shift(2)


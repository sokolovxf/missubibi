# ---- 3.7b  How much of the decline is discontinued product lines? ----------------------
# "Discontinued items may explain part of the downward trend" was carried for several
# versions as a suggestion nobody could act on, because production_status was read in 3.5
# and then dropped before the join. It is cheap to answer: split revenue by fiscal year into
# lines still in production and lines that are not, and look at the year-on-year change once
# the discontinued ones are removed.
#
# This is a DIAGNOSTIC. The forecast target stays total revenue, because that is the number
# the business has to plan for. But if the continuing lines are flat while the total falls,
# the decline is a portfolio decision rather than a demand collapse, and those two call for
# very different plans.
if "production_status" in model_df.columns:
    _ps = model_df["production_status"].fillna("<unknown>").astype(str).str.strip().str.lower()
    _grp = np.where(_ps.str.startswith("discontinue"), "discontinued",
                    np.where(_ps.str.startswith("continue"), "continuing", "other/unknown"))
    _t = (model_df.assign(_g=_grp)
                  .pivot_table(index="fiscal_year", columns="_g", values="revenue",
                               aggfunc="sum")
                  .reindex(FYS).fillna(0.0))
    _t["total"] = _t.sum(axis=1)
    _cont = _t["continuing"] if "continuing" in _t.columns else pd.Series(0.0, index=_t.index)
    _disc = _t["discontinued"] if "discontinued" in _t.columns else pd.Series(0.0, index=_t.index)
    _split = pd.DataFrame({
        "revenue_total": _t["total"],
        "revenue_continuing": _cont,
        "discontinued_%_of_total": 100 * _disc / _t["total"],
        "total_YoY_%": 100 * _t["total"].pct_change(),
        "continuing_YoY_%": 100 * _cont.pct_change(),
    })
    print("\nRevenue by fiscal year, split by production_status\n")
    print(_split.to_string(float_format=lambda x: f"{x:,.1f}"))
    _first, _last = FYS[0], FYS[-1]
    _tot_chg = 100 * (_t["total"].loc[_last] / _t["total"].loc[_first] - 1)
    _con_chg = (100 * (_cont.loc[_last] / _cont.loc[_first] - 1)
                if _cont.loc[_first] > 0 else np.nan)
    print(f"\nFY{_first} -> FY{_last}: total {_tot_chg:+.1f}%, continuing lines only "
          f"{_con_chg:+.1f}%")
    if np.isfinite(_con_chg) and np.isfinite(_tot_chg):
        _gap = _con_chg - _tot_chg
        if abs(_tot_chg) > 5 and _gap > 5:
            note("DATA CHECK",
                 f"Discontinued lines account for a real share of the decline: total revenue "
                 f"moved {_tot_chg:+.1f}% from FY{_first} to FY{_last}, but the lines still in "
                 f"production moved {_con_chg:+.1f}% - a {_gap:.1f} point difference. That is a "
                 f"portfolio decision showing up as a trend. The forecast still targets the "
                 f"total, which is right for planning, but do not read the decline as demand "
                 f"weakness without checking what was withdrawn and whether it was replaced.")
        else:
            note("DATA CHECK",
                 f"Discontinued lines do NOT explain the trend: total revenue moved "
                 f"{_tot_chg:+.1f}% from FY{_first} to FY{_last} and the lines still in "
                 f"production moved {_con_chg:+.1f}%. The decline sits in the continuing "
                 f"portfolio, so it is a demand or pricing question, not a catalogue one.")
else:
    print("\nproduction_status not present in the item export - 3.7b skipped.")

"""## 4. Build the monthly target series

The hierarchy is complete: total, quantity, the top-N categories by revenue, and an
`other` bucket so the components sum to the total exactly (needed later for the
reconciliation check in Section 12). Top categories are ranked on the **initial training
window only**, not the whole period, to avoid leaking test-period information into series
selection.

Clipping policy is decided here too: any series that is ever negative (possible when
returns are kept as negative revenue) has prediction clipping **disabled**, because
clipping predictions at zero while allowing actuals below zero guarantees an error no
model can avoid.
"""

FULL_INDEX = pd.date_range(fy_start(FYS[0]), periods=12 * len(FYS), freq="MS", name="month")
print("modelling index:", FULL_INDEX[0].date(), "->", FULL_INDEX[-1].date(),
      f"({len(FULL_INDEX)} months)")


def monthly_series(df, value_col, index, category=None, cat_col=CAT_COL, exclude=None):
    if category is not None:
        d = df[df[cat_col] == category]
    elif exclude is not None:
        d = df[~df[cat_col].isin(exclude)]
    else:
        d = df
    s = (d.groupby(pd.Grouper(key="sales_order_date", freq="MS"))[value_col].sum()
           .reindex(index, fill_value=0.0).astype(float))
    s.index.name = "month"
    return s



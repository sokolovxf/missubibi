tol = 1e-9 * max(float(series_dict[HIERARCHY["total"]].abs().max()), 1.0)
print(f"\nhierarchy check |total - sum(components)| max = {gap:,.6f}  (tolerance {tol:,.6f})")
assert gap <= tol, "component series do not sum to the total"
print("components sum to the total exactly — forecasts can therefore be reconciled in Section 12.")

# ---- 4.2  Working days per month: the one free exogenous driver -----------------------

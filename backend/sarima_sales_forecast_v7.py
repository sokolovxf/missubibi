# ---- 3.6  Fiscal year, calendar coverage, and robust anomaly detection ----------------
# A fiscal year running Apr..Mar can be named after the calendar year it STARTS in (Japanese
# and Thai practice: FY2021 = Apr-2021..Mar-2022) or the one it ENDS in. Only the label
# changes -- the twelve months inside a fiscal year are identical either way, so no metric,
# fold or forecast below is affected by this setting.
FY_LABEL = str(CONFIG.get("FISCAL_YEAR_LABEL", "end")).lower()
if FY_LABEL not in ("start", "end"):
    raise ValueError("CONFIG['FISCAL_YEAR_LABEL'] must be 'start' or 'end'")


def fiscal_year_vec(dt, start_month=FISCAL_START):
    if FY_LABEL == "start":
        return dt.dt.year - (dt.dt.month < start_month).astype(int)
    return dt.dt.year + (dt.dt.month >= start_month).astype(int)


def fiscal_year(ts, start_month=FISCAL_START):
    ts = pd.Timestamp(ts)
    if FY_LABEL == "start":
        return ts.year - (1 if ts.month < start_month else 0)
    return ts.year + (1 if ts.month >= start_month else 0)


def fy_of(ts):
    return fiscal_year(ts)


def fy_start(fy, start_month=FISCAL_START):
    """First month of fiscal year `fy`. The single place the label convention is turned
    back into a date, so nothing downstream has to know which convention is in force."""
    y = int(fy) if FY_LABEL == "start" else int(fy) - 1
    return pd.Timestamp(year=y, month=start_month, day=1)


print(f"fiscal-year labelling: '{FY_LABEL}' — a year beginning "
      f"{pd.Timestamp(2000, FISCAL_START, 1):%B} {2021} is called "
      f"FY{fiscal_year(pd.Timestamp(2021, FISCAL_START, 1))}")


@contextlib.contextmanager
def capture_warnings(context):
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        yield
    for w in caught:
        FIT_LOG.append({"context": context, "category": w.category.__name__,
                        "message": str(w.message).split("\n")[0][:160]})

def log_failure(context, exc):
    FAILURES.append({"context": context, "error": type(exc).__name__, "message": str(exc)[:200]})

def note(kind, msg):
    """Anything the reader must act on. Collected and re-printed as a checklist in Section 13."""
    NOTES.append({"kind": kind, "message": msg})
    print(f"[{kind}] {msg}")

def warning_summary():
    if not FIT_LOG:
        return pd.DataFrame(columns=["context", "category", "message", "count"])
    return (pd.DataFrame(FIT_LOG).groupby(["context", "category", "message"]).size()
              .reset_index(name="count").sort_values("count", ascending=False))


"""## 12. Forecast the next 12 months

Five things this section gets right that a naive rebuild usually gets wrong:

- **The production spec is the *validated* spec.** It uses the **last walk-forward-validated
  spec** (refreshed as of the final origin), not a fresh AICc selection on all the data —
  which could pick a spec no fold ever actually tested. If selecting on all data would have
  chosen something different, that is reported, not silently substituted.
- **Prediction intervals come from actual out-of-sample walk-forward errors**, by horizon.
  `oos_residual_pool()` collects the errors this model made on months it had not seen, and
  the 90% band is the 5th–95th percentile of those errors added to the point forecast. The
  model's own `conf_int()` — built from in-sample residual variance and systematically too
  narrow — is only a labelled fallback, and `PI_SOURCE` records which was used per series.
- **The plausibility screen runs live here** — this is exactly the code path where a no-op
  screen would be most dangerous, so it is checked in Section 7's self-tests.
- **Forecasts are reconciled.** The bottom-up sum of category forecasts is compared against
  the direct total forecast, and any gap is quantified rather than left implicit.
- **Sensitivity to the anomalous fiscal year.** If a fiscal year flagged in Section 3.7 is a
  data-extraction gap rather than a real decline, every downward forecast is an artifact —
  this section quantifies exactly how much the forecast moves if that year is excluded.
"""


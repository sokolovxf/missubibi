"""## 6. Metrics and fold definitions

- **Pooled metrics are the headline** (computed over all residuals at once), with per-fold
  mean/spread kept as a stability measure — averaging per-fold ratio metrics when each
  `WF1` fold has one observation is a mean of ratios and is badly skewed.
- **One fixed MASE scale per series**, computed on the initial training window only, so
  every fold's MASE is on the same scale and can be averaged and pooled.
- **Bias is measured** (ME, MPE) — a model that is systematically high or low compounds
  over a planning year even if its point-in-time error looks small.
- **MAPE is demoted.** It is unusable with zeros and unstable near them. MASE first, then
  sMAPE, then MAE/RMSE in native units, then MAPE last with its dropped-month count.
"""

def naive_scale_fixed(s, n_ref):
    """MASE denominator: MAE of the lag-1 naive forecast over the INITIAL training window only."""
    v = s.to_numpy(dtype=float)[:n_ref]
    d = np.abs(np.diff(v))
    d = d[np.isfinite(d)]
    if d.size == 0 or np.mean(d) == 0:
        return np.nan
    return float(np.mean(d))


